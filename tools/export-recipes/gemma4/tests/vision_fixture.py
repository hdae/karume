"""**Generates** the image preprocessing fixture of the TS side from the upstream processor.

    cd tools/export-recipes && uv run --with 'transformers==5.14.1' \
        python -m gemma4.tests.vision_fixture

The output is `packages/models/tests/fixtures/gemma4-vision/preprocess.json`. It holds the actual
output of upstream `Gemma4UnifiedImageProcessor`, as sizes and SHA-256 over the bytes, for images
both sides build from the same seed ({@link synthetic_rgb}), so the fixture stays small and the
test compares byte for byte.

MUST: the values come from the upstream processor (and `F.resize` for the resize-only cases) — the
formula is not rewritten here.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any

import numpy as np
import torch

from _shared.paths import REPO_ROOT

FIXTURE = REPO_ROOT / "packages/models/tests/fixtures/gemma4-vision/preprocess.json"

#: `(height, width, budget)`: common shapes, the rule for a side that rounds to 0 in both axes, an
#: upscale, a size the rule leaves as it is (no resize), one axis unchanged, and every budget.
PROCESSOR_CASES: tuple[tuple[int, int, int], ...] = (
    (1024, 1024, 280),
    (480, 640, 280),
    (1080, 1920, 280),
    (1000, 600, 280),
    (333, 517, 280),
    (50, 2000, 280),
    (4, 4000, 280),
    (4000, 4, 280),
    (16, 16, 280),
    (768, 768, 280),
    (768, 500, 280),
    (64, 64, 70),
    (640, 480, 70),
    (640, 480, 140),
    (640, 480, 560),
    (640, 480, 1120),
)

#: `(height, width, target height, target width)` for `F.resize` alone: downscale and upscale in each
#: axis, large factors (a wide support and a low precision against a high one).
RESIZE_CASES: tuple[tuple[int, int, int, int], ...] = (
    (64, 80, 48, 96),
    (200, 131, 96, 48),
    (48, 48, 48, 144),
    (31, 57, 144, 240),
    (300, 200, 192, 96),
    (97, 301, 48, 288),
    (1500, 40, 48, 48),
)


def synthetic_rgb(height: int, width: int, seed: int) -> np.ndarray:
    """`[H, W, 3]` uint8: a gradient per channel plus noise from a 32-bit LCG, so the resize sees
    both smooth areas and values on rounding boundaries. MUST: the same arithmetic as
    `syntheticRgb` in `gemma4_vision_preprocess_test.ts`."""
    state = seed & 0xFFFFFFFF
    out = np.zeros((height, width, 3), dtype=np.uint8)
    for y in range(height):
        for x in range(width):
            for c in range(3):
                state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
                noise = (state >> 24) % 64
                gradient = ((x * (c + 1) * 191) // width + (y * (3 - c) * 127) // height) % 192
                out[y, x, c] = gradient + noise
    return out


def sha256(array: np.ndarray) -> str:
    return hashlib.sha256(array.tobytes()).hexdigest()


def processor_case(processor: Any, height: int, width: int, budget: int, seed: int) -> dict[str, Any]:
    image = synthetic_rgb(height, width, seed)
    # Channels first: a numpy image is taken as it is, without PIL in between.
    features = processor(
        images=[torch.from_numpy(image).permute(2, 0, 1)],
        max_soft_tokens=budget,
        return_tensors="pt",
    )
    tokens = int(features["num_soft_tokens_per_image"][0])
    pixels = features["pixel_values"][0][:tokens].numpy()
    positions = features["image_position_ids"][0][:tokens].numpy()
    if pixels.dtype != np.float32:
        raise TypeError(f"pixel values are {pixels.dtype}, not float32")
    return {
        "height": height,
        "width": width,
        "budget": budget,
        "seed": seed,
        "softTokens": tokens,
        "pixelsSha256": sha256(pixels),
        "positionsSha256": sha256(positions.astype(np.int32)),
    }


def resize_case(height: int, width: int, target_h: int, target_w: int, seed: int) -> dict[str, Any]:
    from torchvision.transforms import InterpolationMode
    from torchvision.transforms.v2 import functional

    image = torch.from_numpy(synthetic_rgb(height, width, seed)).permute(2, 0, 1)
    resized = functional.resize(
        image, [target_h, target_w], interpolation=InterpolationMode.BICUBIC, antialias=True
    )
    return {
        "height": height,
        "width": width,
        "targetHeight": target_h,
        "targetWidth": target_w,
        "seed": seed,
        "sha256": sha256(resized.permute(1, 2, 0).numpy()),
    }


def main() -> None:
    import torchvision
    import transformers
    from transformers import Gemma4UnifiedImageProcessor

    processor = Gemma4UnifiedImageProcessor()
    document = {
        "note": "Generated by tools/export-recipes/gemma4/tests/vision_fixture.py; do not edit.",
        "versions": {
            "transformers": transformers.__version__,
            "torch": torch.__version__,
            "torchvision": torchvision.__version__,
        },
        "processor": [
            processor_case(processor, h, w, budget, 1000 + index)
            for index, (h, w, budget) in enumerate(PROCESSOR_CASES)
        ],
        "resize": [
            resize_case(h, w, th, tw, 2000 + index)
            for index, (h, w, th, tw) in enumerate(RESIZE_CASES)
        ],
    }
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(document, indent=1) + "\n", encoding="utf-8")
    print(FIXTURE, len(document["processor"]), len(document["resize"]))


if __name__ == "__main__":
    main()
