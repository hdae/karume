/**
 * Weight generation of the regression corpus: the bytes of every model-side initializer, made from
 * (seed, initializer name) and the declaration alone, in the codec the distribution stores it in.
 *
 * The value rule keeps a real graph's activations in their working range (uniform random weights
 * saturate the logits at the softcap):
 *
 * - a linear weight has standard deviation 1/sqrt(fanIn): its levels are drawn uniformly and every
 *   scale is 1/(sqrt(fanIn) · d), d the standard deviation of the drawn levels. In `int4-sym-g`, q
 *   uniform in [-7, 7] (stored u = q + 8), d = sqrt(56/3) ≈ 4.32, one scale per group; in
 *   `int2-off`, all four codes u = q + 2 for q in [-2, 1], d = sqrt(5/4), one scale per row; in
 *   `int8-sym`, q uniform in [-127, 127] (stored as a signed byte), d = sqrt((255² − 1)/12), one
 *   scale per row; in `f32`, U(-1, 1) times 1/(sqrt(fanIn) · sqrt(1/3));
 * - a convolution weight takes the linear rule with fanIn the product of its dimensions after the
 *   first (input channels per group × kernel extent);
 * - an embedding table no linear reads takes the linear rule with fanIn 1 (standard deviation 1);
 * - a norm weight is near 1 (1 + U(-0.1, 0.1));
 * - an elementwise operand (a layer scalar, an embedding scale) is U(-1, 1);
 * - a bias (of a linear, a convolution, a layer norm or a group norm) is U(-0.1, 0.1);
 * - an additive operand (a modulation table added to an activation) is U(-0.1, 0.1);
 * - a table that is normalised (the data input of a layer norm) is U(-1, 1).
 *
 * The role comes from the consuming op and input slot ({@link initializerRole}). Only the roles and
 * codecs a corpus entry needs are implemented; anything else throws with the initializer's name and
 * what was found. There is no fallback rule: a guessed rule would let a new entry run on weights
 * nobody chose. Const-region initializers are never generated — they are part of the graph's
 * meaning and come from the graph container.
 *
 * MUST: the bytes this module makes are an invariant of the corpus's sha256 rows. A change here
 * moves every row, so `corpus_weights_test.ts` pins the sha256 of a small tensor per codec and role:
 * a moved pin says the generator changed, not the runtime.
 */

import type { BoundGraph } from "../../src/format/container/bind.ts";
import {
  codecEntry,
  type CodecName,
  groupScaleShape,
  payloadBytes,
} from "../../src/format/container/codecs.ts";
import type { IrDeclaration } from "../../src/format/ir.ts";
import { fillWords, randomStream, type RandomStream, signedUnit } from "./random.ts";

/** How the distribution stores one model-side initializer (the fields of its binding's encoding). */
export type StoredEncoding = {
  readonly codec: CodecName;
  readonly groupSize?: number;
  readonly rowAxis?: 0 | 1;
};

/** The generated bytes of one initializer: the payload, and the scale of a quantized codec. */
export type GeneratedTensor = {
  readonly encoding: StoredEncoding;
  readonly bytes: Uint8Array<ArrayBuffer>;
  readonly scale?: Uint8Array<ArrayBuffer>;
};

/** What an initializer is to the graph, as far as its value rule is concerned. */
export type WeightRole =
  | { readonly kind: "linear"; readonly fanIn: number }
  | { readonly kind: "convolution"; readonly fanIn: number }
  | { readonly kind: "embedding" }
  | { readonly kind: "norm" }
  | { readonly kind: "operand" }
  | { readonly kind: "bias" }
  | { readonly kind: "additive" }
  | { readonly kind: "normalized" };

/** An initializer the corpus has no generation rule for. */
export class CorpusWeightError extends Error {
  override readonly name = "CorpusWeightError";
}

/**
 * Consumer (`op#slot`) → what that slot makes of the initializer. A consumer outside this table has
 * no rule: add one only together with the value rule it needs.
 */
const CONSUMER_KINDS: Readonly<Record<string, WeightRole["kind"]>> = {
  "linear#1": "linear",
  "embedding#0": "embedding",
  "conv1d#1": "convolution",
  "conv2d#1": "convolution",
  "conv3d#1": "convolution",
  "rms_norm#1": "norm",
  "layer_norm#1": "norm",
  "group_norm#1": "norm",
  "mul#1": "operand",
  "linear#2": "bias",
  "layer_norm#2": "bias",
  "conv1d#2": "bias",
  "conv2d#2": "bias",
  "conv3d#2": "bias",
  "group_norm#2": "bias",
  "add#0": "additive",
  "add#1": "additive",
  "layer_norm#0": "normalized",
};

/** Elements of a shape. */
const numelOf = (shape: readonly number[]): number => shape.reduce((count, dim) => count * dim, 1);

/** The `op#slot` of every node that reads `name`, in node order, without repeats. */
const consumersOf = (declaration: IrDeclaration, name: string): string[] => {
  const found: string[] = [];
  for (const node of declaration.nodes) {
    node.ins.forEach((input, slot) => {
      const consumer = `${node.op}#${slot}`;
      if (input === name && !found.includes(consumer)) found.push(consumer);
    });
  }
  return found;
};

/**
 * The role of initializer `name`, from what consumes it.
 *
 * A table read both by `embedding` (slot 0) and by `linear` (slot 1) is a tied embedding: it is
 * stored and quantized for the linear, so it takes the linear's rule; a table only `embedding`
 * reads is an embedding table. Any other mix of roles, a consumer outside the table, or no consumer
 * at all throws.
 */
export const initializerRole = (declaration: IrDeclaration, name: string): WeightRole => {
  const value = Object.hasOwn(declaration.values, name) ? declaration.values[name] : undefined;
  if (value === undefined || !Object.hasOwn(declaration.initializers, name)) {
    throw new CorpusWeightError(`initializer '${name}' is not declared by the graph`);
  }
  if (value.dtype !== "f32") {
    throw new CorpusWeightError(
      `initializer '${name}' has dtype ${value.dtype}: an integer table carries meaning and cannot be generated — it belongs in the graph container's const region`,
    );
  }
  const consumers = consumersOf(declaration, name);
  if (consumers.length === 0) {
    throw new CorpusWeightError(
      `initializer '${name}' is read by no node, so its role cannot be told`,
    );
  }
  const unknown = consumers.filter((consumer) => !Object.hasOwn(CONSUMER_KINDS, consumer));
  if (unknown.length > 0) {
    throw new CorpusWeightError(
      `initializer '${name}' is read by [${consumers.join(", ")}]: no generation rule for [${unknown.join(", ")}] (add the consumer and its value rule to the corpus generator)`,
    );
  }
  const kinds = new Set(consumers.map((consumer) => CONSUMER_KINDS[consumer]));
  const shape = value.shape.map(Number);
  if (
    kinds.has("linear") &&
    [...kinds].every((kind) => kind === "linear" || kind === "embedding")
  ) {
    if (shape.length !== 2) {
      throw new CorpusWeightError(
        `initializer '${name}' is a linear weight of rank ${shape.length} ([${shape.join(",")}]): the rule needs [out, in]`,
      );
    }
    return { kind: "linear", fanIn: shape[1] };
  }
  if (kinds.size === 1 && kinds.has("convolution")) {
    if (shape.length < 3) {
      throw new CorpusWeightError(
        `initializer '${name}' is a convolution weight of rank ${shape.length} ([${shape.join(",")}]): the rule needs [out, in per group, ...kernel]`,
      );
    }
    return { kind: "convolution", fanIn: numelOf(shape.slice(1)) };
  }
  if (kinds.size === 1 && kinds.has("embedding")) {
    if (shape.length !== 2) {
      throw new CorpusWeightError(
        `initializer '${name}' is an embedding table of rank ${shape.length} ([${shape.join(",")}]): the rule needs [rows, width]`,
      );
    }
    return { kind: "embedding" };
  }
  if (kinds.size === 1 && kinds.has("norm")) return { kind: "norm" };
  if (kinds.size === 1 && kinds.has("operand")) return { kind: "operand" };
  if (kinds.size === 1 && kinds.has("bias")) return { kind: "bias" };
  if (kinds.size === 1 && kinds.has("additive")) return { kind: "additive" };
  if (kinds.size === 1 && kinds.has("normalized")) return { kind: "normalized" };
  throw new CorpusWeightError(
    `initializer '${name}' is read by [${consumers.join(", ")}]: these consumers ask for different value rules, so its role cannot be told`,
  );
};

/** Words drawn per refill of the scratch buffer (generation never allocates per element). */
const CHUNK_WORDS = 1 << 16;

/** f32 values `value(signedUnit(word))`, one word per element. */
const generateF32 = (
  stream: RandomStream,
  count: number,
  value: (unit: number) => number,
): Uint8Array<ArrayBuffer> => {
  const out = new Float32Array(count);
  const scratch = new Uint32Array(Math.min(CHUNK_WORDS, Math.max(count, 1)));
  for (let start = 0; start < count; start += scratch.length) {
    const length = Math.min(scratch.length, count - start);
    fillWords(stream, scratch, length);
    for (let i = 0; i < length; i += 1) out[start + i] = value(signedUnit(scratch[i]));
  }
  return new Uint8Array(out.buffer);
};

/**
 * 16 random bits → one payload byte of two nibbles. Each random byte picks u = 1 + ⌊15 b / 256⌋,
 * so q = u − 8 covers [-7, 7] (one level takes 18 of the 256 byte values, the others 17).
 */
const nibblePairTable = (): Uint8Array<ArrayBuffer> => {
  const table = new Uint8Array(1 << 16);
  for (let bits = 0; bits < table.length; bits += 1) {
    const low = 1 + (((bits & 0xff) * 15) >> 8);
    const high = 1 + (((bits >>> 8) * 15) >> 8);
    table[bits] = low | (high << 4);
  }
  return table;
};

/** The standard deviation of q uniform over the 15 levels [-7, 7]: sqrt((15² − 1) / 12). */
const INT4_LEVEL_DEVIATION = Math.sqrt(56 / 3);

/** The standard deviation of q uniform over the 4 levels [-2, 1]: sqrt((4² − 1) / 12). */
const INT2_LEVEL_DEVIATION = Math.sqrt(5 / 4);

/** The standard deviation of q uniform over the 255 levels [-127, 127]: sqrt((255² − 1) / 12). */
const INT8_LEVEL_DEVIATION = Math.sqrt((255 * 255 - 1) / 12);

/** The standard deviation of U(-1, 1): sqrt(1/3). */
const UNIT_DEVIATION = Math.sqrt(1 / 3);

/** The group size of a quantized linear weight, which must be stored with rows on axis 0. */
const rowGroupSize = (name: string, encoding: StoredEncoding): number => {
  if (encoding.groupSize === undefined) {
    throw new CorpusWeightError(
      `initializer '${name}': codec '${encoding.codec}' needs a groupSize`,
    );
  }
  if ((encoding.rowAxis ?? 0) !== 0) {
    throw new CorpusWeightError(
      `initializer '${name}': codec '${encoding.codec}' with rowAxis ${encoding.rowAxis} has no generation rule (rows on axis 0 only)`,
    );
  }
  return encoding.groupSize;
};

/** Every scale step equal to `step`, in the scale shape of (shape, rows on axis 0, groupSize). */
const constantScale = (
  shape: readonly number[],
  groupSize: number,
  step: number,
): Uint8Array<ArrayBuffer> => {
  const [rows, groups] = groupScaleShape(shape, 0, groupSize);
  const scale = new Float32Array(rows * groups);
  scale.fill(step);
  return new Uint8Array(scale.buffer);
};

const generateInt4Linear = (
  name: string,
  stream: RandomStream,
  shape: readonly number[],
  encoding: StoredEncoding,
  fanIn: number,
): GeneratedTensor => {
  const groupSize = rowGroupSize(name, encoding);
  const bytes = new Uint8Array(
    payloadBytes(encoding.codec, numelOf(shape), `initializer '${name}'`),
  );
  // One word fills two payload bytes (four nibbles); the packing makes the payload a multiple of 4.
  const table = nibblePairTable();
  const scratch = new Uint32Array(CHUNK_WORDS);
  const words = bytes.byteLength / 2;
  for (let start = 0; start < words; start += scratch.length) {
    const length = Math.min(scratch.length, words - start);
    fillWords(stream, scratch, length);
    for (let i = 0; i < length; i += 1) {
      const word = scratch[i];
      const at = (start + i) * 2;
      bytes[at] = table[word & 0xffff];
      bytes[at + 1] = table[word >>> 16];
    }
  }
  return {
    encoding,
    bytes,
    scale: constantScale(shape, groupSize, 1 / (Math.sqrt(fanIn) * INT4_LEVEL_DEVIATION)),
  };
};

/**
 * `int2-off`: every 2-bit code u = q + 2 is equally likely, so the payload is the stream's words
 * themselves, written low byte first (the same bytes on every machine). A per-channel codec: one
 * scale per row.
 */
const generateInt2Linear = (
  name: string,
  stream: RandomStream,
  shape: readonly number[],
  encoding: StoredEncoding,
  fanIn: number,
): GeneratedTensor => {
  const groupSize = rowGroupSize(name, encoding);
  const bytes = new Uint8Array(
    payloadBytes(encoding.codec, numelOf(shape), `initializer '${name}'`),
  );
  // The packing (16 elements in 4 bytes) makes the payload a multiple of 4.
  const scratch = new Uint32Array(CHUNK_WORDS);
  const words = bytes.byteLength / 4;
  for (let start = 0; start < words; start += scratch.length) {
    const length = Math.min(scratch.length, words - start);
    fillWords(stream, scratch, length);
    for (let i = 0; i < length; i += 1) {
      const word = scratch[i];
      const at = (start + i) * 4;
      bytes[at] = word & 0xff;
      bytes[at + 1] = (word >>> 8) & 0xff;
      bytes[at + 2] = (word >>> 16) & 0xff;
      bytes[at + 3] = word >>> 24;
    }
  }
  return {
    encoding,
    bytes,
    scale: constantScale(shape, groupSize, 1 / (Math.sqrt(fanIn) * INT2_LEVEL_DEVIATION)),
  };
};

/**
 * A random byte b → the stored byte of q = −127 + ⌊255 b / 256⌋ (two's complement), so q covers
 * [-127, 127] and never -128 (one level takes 2 of the 256 byte values, the others 1).
 */
const int8LevelTable = (): Uint8Array<ArrayBuffer> => {
  const table = new Uint8Array(256);
  for (let bits = 0; bits < table.length; bits += 1)
    table[bits] = (-127 + ((bits * 255) >> 8)) & 0xff;
  return table;
};

/** `int8-sym`: one byte per element, four per random word (low byte first). One scale per row. */
const generateInt8Linear = (
  name: string,
  stream: RandomStream,
  shape: readonly number[],
  encoding: StoredEncoding,
  fanIn: number,
): GeneratedTensor => {
  const groupSize = rowGroupSize(name, encoding);
  const count = payloadBytes(encoding.codec, numelOf(shape), `initializer '${name}'`);
  const bytes = new Uint8Array(count);
  const table = int8LevelTable();
  const scratch = new Uint32Array(CHUNK_WORDS);
  const words = Math.ceil(count / 4);
  for (let start = 0; start < words; start += scratch.length) {
    const length = Math.min(scratch.length, words - start);
    fillWords(stream, scratch, length);
    for (let i = 0; i < length; i += 1) {
      const word = scratch[i];
      const at = (start + i) * 4;
      for (let lane = 0; lane < 4 && at + lane < count; lane += 1) {
        bytes[at + lane] = table[(word >>> (lane * 8)) & 0xff];
      }
    }
  }
  return {
    encoding,
    bytes,
    scale: constantScale(shape, groupSize, 1 / (Math.sqrt(fanIn) * INT8_LEVEL_DEVIATION)),
  };
};

/** One initializer to generate. */
export type TensorSpec = {
  readonly name: string;
  readonly shape: readonly number[];
  readonly role: WeightRole;
  readonly encoding: StoredEncoding;
};

/** The bytes of one initializer under `seed` (deterministic in (seed, name, shape, role, codec)). */
export const generateTensor = (spec: TensorSpec, seed: number): GeneratedTensor => {
  const { name, shape, role, encoding } = spec;
  const stream = randomStream(seed, name);
  const entry = codecEntry(encoding.codec);
  if (encoding.codec === "f32" && role.kind === "norm") {
    return { encoding, bytes: generateF32(stream, numelOf(shape), (unit) => 1 + 0.1 * unit) };
  }
  if (encoding.codec === "f32" && role.kind === "operand") {
    return { encoding, bytes: generateF32(stream, numelOf(shape), (unit) => unit) };
  }
  if (encoding.codec === "f32" && (role.kind === "bias" || role.kind === "additive")) {
    return { encoding, bytes: generateF32(stream, numelOf(shape), (unit) => 0.1 * unit) };
  }
  if (encoding.codec === "f32" && role.kind === "normalized") {
    return { encoding, bytes: generateF32(stream, numelOf(shape), (unit) => unit) };
  }
  const fanIn = linearRuleFanIn(role);
  if (encoding.codec === "f32" && fanIn !== undefined) {
    const step = 1 / (Math.sqrt(fanIn) * UNIT_DEVIATION);
    return { encoding, bytes: generateF32(stream, numelOf(shape), (unit) => unit * step) };
  }
  if (encoding.codec === "int4-sym-g" && fanIn !== undefined) {
    return generateInt4Linear(name, stream, shape, encoding, fanIn);
  }
  if (encoding.codec === "int2-off" && fanIn !== undefined) {
    return generateInt2Linear(name, stream, shape, encoding, fanIn);
  }
  if (encoding.codec === "int8-sym" && fanIn !== undefined) {
    return generateInt8Linear(name, stream, shape, encoding, fanIn);
  }
  throw new CorpusWeightError(
    `initializer '${name}': no generation rule for a ${role.kind} weight stored in codec '${encoding.codec}' (layout ${entry.layout}); the corpus generates f32 norm weights, operands, biases, additive operands and normalised tables, and linear weights, convolution weights and embedding tables in f32, int4-sym-g, int2-off and int8-sym`,
  );
};

/**
 * The fan-in of a role that takes the linear rule: a linear or convolution weight's own, 1 for an
 * embedding table (standard deviation 1). `undefined` for the other roles.
 */
const linearRuleFanIn = (role: WeightRole): number | undefined => {
  if (role.kind === "linear" || role.kind === "convolution") return role.fanIn;
  if (role.kind === "embedding") return 1;
  return undefined;
};

/**
 * Generates every model-side initializer of `bound` (a graph container's or a distribution's merge
 * result) in its stored encoding.
 *
 * `encodings` names exactly the initializers to generate: every non-shared initializer that is not
 * supplied from the const region. A const named there, a model-side initializer missing from it, or
 * a name the graph does not declare throws.
 */
export const generateWeights = (
  bound: BoundGraph,
  encodings: ReadonlyMap<string, StoredEncoding>,
  seed: number,
): ReadonlyMap<string, GeneratedTensor> => {
  const { declaration } = bound;
  const generated = new Map<string, GeneratedTensor>();
  for (const [name, init] of Object.entries(declaration.initializers)) {
    if (init.shared) continue;
    if (bound.supplies.get(name)?.origin === "const") {
      if (encodings.has(name)) {
        throw new CorpusWeightError(
          `initializer '${name}' is supplied by the const region, which is read from the graph container and never generated: remove it from the storage table`,
        );
      }
      continue;
    }
    const encoding = encodings.get(name);
    if (encoding === undefined) {
      throw new CorpusWeightError(
        `initializer '${name}' is a model-side weight without a stored encoding: the storage table must name it`,
      );
    }
    const shape = declaration.values[name].shape.map(Number);
    generated.set(
      name,
      generateTensor({ name, shape, role: initializerRole(declaration, name), encoding }, seed),
    );
  }
  const surplus = [...encodings.keys()].filter((name) => !generated.has(name));
  if (surplus.length > 0) {
    throw new CorpusWeightError(
      `the storage table names [${surplus.join(", ")}], which are not model-side initializers of the graph`,
    );
  }
  return generated;
};

/** The codecs {@link perturbOneLevel} can move a level in. */
export const PERTURBABLE_CODECS: readonly CodecName[] = [
  "int4-sym-g",
  "int2-off",
  "int8-sym",
  "f32",
];

/**
 * The same tensor with element 0 moved by one quantization level (u → u + 1, or u − 1 at the top
 * level; in `f32`, one unit in the last place, away from zero): the smallest change a stored weight
 * can make, for checking that the corpus's comparisons can fail.
 */
export const perturbOneLevel = (name: string, tensor: GeneratedTensor): GeneratedTensor => {
  const bytes = tensor.bytes.slice();
  if (tensor.encoding.codec === "int4-sym-g") {
    // Element 0 is the low nibble of byte 0 (the i4 pack order).
    const level = bytes[0] & 0x0f;
    bytes[0] = (bytes[0] & 0xf0) | (level < 15 ? level + 1 : level - 1);
    return { ...tensor, bytes };
  }
  if (tensor.encoding.codec === "int2-off") {
    // Element 0 is the low 2 bits of byte 0 (the i2 pack order).
    const level = bytes[0] & 0x03;
    bytes[0] = (bytes[0] & 0xfc) | (level < 3 ? level + 1 : level - 1);
    return { ...tensor, bytes };
  }
  if (tensor.encoding.codec === "int8-sym") {
    // Element 0 is byte 0, a signed level in [-127, 127].
    const level = (bytes[0] << 24) >> 24;
    bytes[0] = (level < 127 ? level + 1 : level - 1) & 0xff;
    return { ...tensor, bytes };
  }
  if (tensor.encoding.codec === "f32") {
    // Element 0 is the first word; its bit pattern + 1 is the next value away from zero (− 1 at the
    // largest finite magnitude, which + 1 would turn into an infinity).
    const words = new Uint32Array(bytes.buffer, 0, 1);
    const values = new Float32Array(bytes.buffer, 0, 1);
    words[0] += 1;
    if (!Number.isFinite(values[0])) words[0] -= 2;
    return { ...tensor, bytes };
  }
  throw new CorpusWeightError(
    `initializer '${name}': perturbing one level is defined for ${PERTURBABLE_CODECS.join(", ")}, not '${tensor.encoding.codec}'`,
  );
};
