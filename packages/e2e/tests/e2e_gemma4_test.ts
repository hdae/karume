// Real-GPU golden E2E of real-weight Gemma 4 E2B (1-shot causal LM) — acceptance that **mixed
// storage (embedding i8 × linear i4) and the two layer types of attention take effect on the real
// model**.
//
// `e2e_minicpm5_greedy_test.ts` is the mirror original that owns "true GQA gives correct numbers
// as a 24-layer language model"; what this one adds are the 3 points specific to Gemma 4:
//
// - **MQA 8:1** (one k / v head — a stronger degeneration than minicpm5's 16:2)
// - **Per-layer-type D** (sliding layers have head_dim 256 / full layers 512. `hidden_size / heads`
//   = 192 differs from both, so checking every layer with one of the values leaves the rest
//   entirely unchecked)
// - **Mixed quantization** (ADR 0069 decision 5 — a vocabulary of 262144 × 35 PLE tables is the
//   shape "the embeddings are most of the weights", so neither i4 alone nor i8 alone works)
//
// 4 checks:
//
// ① Form + storage breakdown (the head axes / per-layer-type D of the 35 attentions, the count of
//    initializers per storage dtype)
// ② Tolerance comparison of the logits (torch CPU expected values, 3 cases) —
//    {@link GEMMA4_TOLERANCE}
// ③ Greedy match at the last position (a semantic line independent of ②: the top-1 does not move
//    even when the numbers drift)
// ④ Census (proof that `attention_qk` / `attention_pv` are all `:gqa` + linear / embedding **ran
//    with compressed-storage keys** = nothing silently fell out of eligibility and was expanded to
//    f32)
//
// The target is `outputs/series/gemma4-e2b/` (even with mixed storage it is 3.97GiB, so it is
// outside the repository — `outputs/` in `.gitignore`. The canonical spelling of the 3 asset roots
// is in tools/export-recipes/_shared/paths.py and docs/assets-layout.md). It is generated by
// `tools/export-recipes/gemma4/export.py` (GENERATE_COMMAND below is the canonical command), and
// the source of truth for the storage breakdown and the layer layout is its `assert_ir_form`.
//
// The 1-shot graph is not shipped by any distribution (models/karume-gemma4 carries only the
// product decode graph), so every case here is an implementation-time series check (ADR 0139
// decision 6): it runs only with KARUME_SERIES=1 and SKIPs explicitly otherwise. The shipped
// graph's sha rows and census are covered by e2e_gemma4_reference_test.ts and
// e2e_gemma4_quant_test.ts.
//
// No KV cache is involved (1-shot = a single path equivalent to prefill. The acceptance of
// states-form decode and KV sharing is packages/models/tests/e2e_gemma4_greedy_test.ts).
//
// Without the assets the cases **SKIP explicitly**. ADR 0005's "an all-SKIP run is an explicit
// FAIL" guard (tests/gpu_gate_test.ts) looks only at *whether a GPU adapter exists*, independent of
// this SKIP. Conversely, assets that are **partially** present (missing cases) FAIL rather than
// SKIP (the "asset completeness" test below) — that would otherwise be a silent apparent success.

