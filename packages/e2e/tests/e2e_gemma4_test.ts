/** Reads `io.<case>.safetensors` and builds the `Tensor` table of one set of graph inputs. */
const loadCase = async (
  caseName: string,
  inputSpecs: readonly { readonly name: string; readonly dtype: "f32" | "i32" | "bool" }[],
): Promise<{ readonly inputs: Record<string, Tensor>; readonly expected: Tensor }> => {
  const io = parseSafetensors(await readBuffer(SERIES_ROOT, `${IO_PREFIX}${caseName}${IO_SUFFIX}`));
  // Every io tensor corresponds exactly to the graph's inputs and outputs (nothing extra, nothing
  // missing).
  assertEquals(
    [...io.tensors.keys()].sort(),
    [...inputSpecs.map((spec) => `input.${spec.name}`), "output.0"].sort(),
    `tensor keys of ${IO_PREFIX}${caseName}${IO_SUFFIX}`,
  );
  const inputs: Record<string, Tensor> = {};
  for (const spec of inputSpecs) {
    const view = io.tensors.get(`input.${spec.name}`);
    assert(view !== undefined, `input.${spec.name} is not in the golden of ${caseName}`);
    inputs[spec.name] = ioTensor(io, view, spec.dtype);
  }
  const output = io.tensors.get("output.0");
  assert(output !== undefined, `output.0 is not in the golden of ${caseName}`);
  return { inputs, expected: ioTensor(io, output, "f32") };
};

/**
 * The logits of the last position (row T−1 of `[1,T,V]`). ③'s greedy and the sha artifact look at
 * **the same row** (keeping the slice in two places would allow a shape where only one of them is
 * off by a position).
 */
const lastLogits = (logits: Tensor, where: string): Float32Array<ArrayBuffer> => {
  assert(logits.dtype === "f32", `${where}: logits are not f32`);
  assertEquals(logits.shape.length, 3, `${where}: logits rank`);
  const vocab = logits.shape[2];
  return logits.data.subarray((logits.shape[1] - 1) * vocab, logits.shape[1] * vocab);
};

/**
 * The top-1 token of the last position (row T−1 of `[1,T,V]`) and **its gap to the second**.
 *
 * The scan compares strictly with `>`, so on a tie **the smaller index** stays (the GPU side and
 * the golden side use the same rule). `margin` is the decision's slack itself: "a numeric
 * difference smaller than this gap does not move the top-1".
 */
const greedyTop = (
  logits: Tensor,
  where: string,
): { readonly top: number; readonly margin: number } => {
  const row = lastLogits(logits, where);
  let top = 0;
  let best = row[0];
  let second = Number.NEGATIVE_INFINITY;
  for (let index = 1; index < row.length; index += 1) {
    const value = row[index];
    if (value > best) {
      second = best;
      best = value;
      top = index;
    } else if (value > second) {
      second = value;
    }
  }
  return { top, margin: best - second };
};

/**
 * ① Form and storage breakdown (looks only at the properties that **break silently while the
 * numbers still match**).
 *
 * MUST: do not drop this check. An asset in the materialized `repeat_kv` form (Hkv=8) has
 * **exactly the same numbers**, so it slips through both ②'s tolerance comparison and ③'s greedy,
 * and only the meaning of an MQA acceptance silently disappears (the reader side checks the same
 * property export.py's `assert_ir_form` checks on the writer side). Per-layer-type D and the
 * storage breakdown have the same property — the former's numbers match with cases of T ≤ 512
 * only, and the latter gives correct values even after dropping to f32.
 */
const assertGemma4Form = (model: PreparedModel): number => {
  const graph = model.graph;
  const attentions = graph.nodes.filter((node) => node.op === "attention");
  assertEquals(attentions.length, LAYERS, "attention node count (= layer count)");
  attentions.forEach((node, layer) => {
    const type = FULL_LAYERS.has(layer) ? "full" : "sliding";
    // A 1-shot attention has 4 inputs q / k / v / mask (the states form has 3 — the decode
    // check's job).
    const shapes = node.ins.slice(0, 3).map((name) => graph.values[name].shape);
    assertEquals(
      shapes.map((shape) => shape[1]),
      [HEADS, KV_HEADS, KV_HEADS],
      `attention[${layer}] (${type}): head axis`,
    );
    assertEquals(
      shapes.map((shape) => shape[3]),
      [headDimOf(layer), headDimOf(layer), headDimOf(layer)],
      `attention[${layer}] (${type}): D axis (the layer type's head_dim)`,
    );
  });

  const census: Record<string, number> = {};
  for (const initializer of Object.values(graph.initializers)) {
    // A shared (borrowed) initializer declares no storage — this model has none.
    if (initializer.storage === undefined) continue;
    const layout = codecLayout(initializer.storage.codec);
    census[layout] = (census[layout] ?? 0) + 1;
  }
  for (const [dtype, expected] of Object.entries(STORAGE_EXPECTATION)) {
    assertEquals(
      Object.hasOwn(census, dtype) ? census[dtype] : 0,
      expected,
      `initializer count of storage ${dtype} (full breakdown ${JSON.stringify(census)}) — ` +
        `a weight that fails the eligibility check silently stays f32`,
    );
  }
  return attentions.length;
};

