/** One golden case run through the shared Session (preconditions already asserted). */
type GoldenRun = {
  readonly actual: Tensor;
  readonly expected: Tensor;
  readonly outputName: string;
  readonly where: string;
};

/**
 * Opens the 1-shot graph once and hands `body` a runner over one Session, so the default sha case
 * and the opt-in parity case share the same lifecycle, form check and adapter identity check.
 *
 * The runner loads `io.<case>.safetensors`, runs it and asserts the output keys, shape and dtype
 * (structure checks that hold without any tolerance).
 */
const withGoldenSession = async (
  body: (runCase: (caseName: string) => Promise<GoldenRun>) => Promise<void>,
): Promise<void> => {
  const parsed = prepareContainer(
    await openSeriesContainer(new URL(MODEL_FILE, SERIES_ROOT)),
    GRAPH_NAME,
  );
  assertEquals(
    parsed.graph.inputs.map((spec) => spec.name),
    ["input_ids"],
    "graph inputs",
  );
  assertEquals(parsed.graph.outputs.length, 1, "graph.outputs count (one logits output, 1-shot)");
  const outputName = parsed.graph.outputs[0];
  const declared = parsed.graph.values[outputName].dtype;
  // MUST: the numeric checks also hold the form and storage check independently — the census
  // below is a separate test, so wiring it only there would (in a setup where only the census is
  // red / SKIPs) let an asset re-exported to the materialized `repeat_kv` form or one dropped to
  // f32 pass on numbers alone, and it would no longer be an MQA / mixed-storage acceptance.
  assertGemma4Form(parsed);

  const gpu = await acquireGpu();
  // MUST: destroying the device also covers failures of the adapter check and of
  // `createSession`. If missed, the rest of that run proceeds holding an undestroyed device and
  // later tests go red with OOM (the deferred release in known-issues).
  try {
    // This path records reference values and results as this machine's rows, so the identity of
    // the adapter the key was taken from and the adapter that runs is checked here (a mix-up on a
    // multi-GPU machine would measure against another machine's band).
    assertAdapterMatchesEnvironment(gpu);
    const session = await parsed.createContainerSession(gpu);
    try {
      await body(async (caseName) => {
        const { inputs, expected } = await loadCase(caseName, parsed.graph.inputs);
        const outputs = await session.run(inputs);
        assertEquals(Object.keys(outputs).sort(), [...parsed.graph.outputs].sort());
        const actual = outputs[outputName];
        const where = `${caseName} output.0 ('${outputName}')`;
        assertEquals(actual.shape, expected.shape, `${where}: shape`);
        assertEquals(actual.dtype, declared, `${where}: dtype`);
        return { actual, expected, outputName, where };
      });
    } finally {
      await session.dispose();
    }
  } finally {
    gpu.destroy();
  }
};

/**
 * Default run: the last-position logits row of each case is settled against this machine's sha256
 * reference row (ADR 0106), plus the constant-output gate over the per-case top-1 tokens. Neither
 * compares with the torch golden, so both stay in the default lanes; the torch comparison (② / ③)
 * is the opt-in case below. One Session crosses T = 6 / 10 / 598 here as well (see that case's
 * JSDoc for why).
 */
test.skipIf(!AVAILABLE || !GPU_AVAILABLE)(
  `Gemma 4 E2B golden: sha256 reference rows of the 3 cases' last-position logits and the constant-output check (real GPU)${SERIES_CHECKS_OPT_IN}`,
  async () => {
    /**
     * The duration of the whole series (carried by the settlement of a run that failed outside
     * the cases).
     */
    const seriesStartedAt = performance.now();
    /**
     * Whether a case's catch already left a settlement (if so, the series slot is not filled
     * twice).
     */
    let caseSettled = false;
    try {
      await withGoldenSession(async (runCase) => {
        /**
         * The last-position top-1 per case (all cases identical = used to detect a constant
         * output).
         */
        const tops: number[] = [];
        /**
         * Diagnostics of the cases that disagreed with the reference rows. After each case's
         * settlement is recorded in its slot, they fail together **after every case has run**
         * (throwing midway would leave the measured shas of the remaining cases out of the
         * results).
         */
        const mismatches: string[] = [];
        for (const caseName of CASES) {
          let settlement: ReferenceSettlement | undefined;
          await runRecordedCase(
            results,
            {
              id: caseName,
              // The settlement stays in the case's slot — the series catch does not record it
              // twice.
              onFailure: () => {
                caseSettled = true;
              },
            },
            async () => {
              const { actual, outputName } = await runCase(caseName);
              tops.push(greedyTop(actual, `${caseName} GPU`).top);

              // The same last row that greedyTop reads becomes the artifact (one safetensors file,
              // no metadata) and is checked against this machine's reference row; settleOrObserve
              // skips only the comparison when the row is missing in compare mode.
              const row = lastLogits(actual, `${caseName} GPU`);
              const outcome = await settleOrObserve(references, results, {
                id: caseName,
                artifact: `${caseName}-last-logits.safetensors`,
                bytes: f32ArtifactBytes(outputName, [1, row.length], row),
              });
              settlement = outcome.settlement;
              return outcome.fields;
            },
          );
          if (settlement?.check.status === "fail") {
            mismatches.push(referenceMismatchMessage(caseName, settlement, references));
          }
        }
        // Fail on sha mismatches before the tautology check (if the check threw first, the
        // mismatch diagnostics would not be printed — the settlements are already in each case's
        // slot, so the order exists only for the diagnostics).
        if (mismatches.length > 0) {
          // The mismatch settlements are in each case's slot — the series catch does not record
          // them twice.
          caseSettled = true;
          throw new Error(mismatches.join("\n"));
        }
        // The tautology check: if every case's top-1 is the same, the output is constant (the
        // runtime side also gets the independent line export.py's `_sanity` has). The expected
        // values are the 2 kinds ` Paris` / `東京` (export.py's `GREEDY_EXPECTATIONS`).
        assert(
          new Set(tops).size > 1,
          `every case's last-position top-1 is the same ${tops[0]} — a constant output`,
        );
      });
    } catch (cause) {
      // A run that failed outside the cases (reading assets, building the Session, the tautology
      // check, the release) is also recorded in a slot. Leaving without a settlement would let
      // the settlement of an earlier run the same day stay in this slot. A run where a case
      // itself failed is already in that case's slot, so nothing is recorded here.
      if (!caseSettled) {
        await recordFailure(results, {
          id: "series",
          status: "fail",
          elapsedMs: Math.round(performance.now() - seriesStartedAt),
          note: `failed outside the cases: ${cause instanceof Error ? cause.message : String(cause)}`,
        });
      }
      throw cause;
    }
  },
);

