/**
 * The tolerance for comparing the raw logits (`[1,T,262144]`) with the torch CPU expected values.
 *
 * Measured (first real run 2026-08-19, a plain comparison with `atol=rtol=0`, 3 cases × 1 output —
 * maxAbs matched exactly between the smoke run and the official run = deterministic):
 *
 * | Case       | T   | maxAbs   | maxRel  |
 * | ---------- | --- | -------- | ------- |
 * | capital-en | 6   | 1.802e-4 | 7.46e-1 |
 * | capital-ja | 10  | 2.680e-4 | 6.84e-1 |
 * | context-en | 598 | 2.232e-3 | 4.37e+2 |
 *
 * atol 1e-2 is about 4.5 times the measured worst 2.232e-3 (context-en). maxRel jumps because of
 * reference elements near 0 (allclose clips the denominator from below — the same shape as the
 * other real-weight checks), so the decision rests on atol alone.
 *
 * The worst, context-en's 2.23e-3, is one and a half orders of magnitude above minicpm5 (7.44e-5),
 * a level explained by 3 points: softcap pins the logits' range to |x| ≤ 30 (relative ~7e-5), T
 * and D (512) are large so the reductions are deep, and the sample is 157 million elements. The
 * greedy check's validity condition (golden margin > 2×atol) has a minimum margin of 3.56, 178
 * times atol 1e-2 — the decision does not waver.
 *
 * **rtol is 0** (the decision rests on atol alone) — the same shape as the other real-weight checks
 * (DeBERTa / EmbeddingGemma / MiniCPM5). When a reference element is exactly 0.0, allclose clips
 * the denominator from below at 1e-12, so maxRel jumps, but that element's absolute error is far
 * below atol. Once the measurement table is filled in, this paragraph too is restated from the
 * measurement as "was it that shape".
 *
 * The error comes from the same sources as the other real-weight checks (fma fusion, a reduction
 * order of linear / rms_norm / attention different from torch's, implementation differences of
 * transcendental functions), plus this series' own **dequant path** — but the rounding is done by
 * the export side's fake-quant before the reference (ADR 0006), and the GPU's `f32(q) * scale` is
 * **the same f32 product** as torch's `round(w/s)*s`, so by design storing as i4 / i8 adds no error
 * by itself. If that broke, it would show as a measurement orders of magnitude worse than the
 * other series.
 *
 * NOTE: one case looks at a vocabulary of 262144 × the longest T=598 = 157 million elements, so the
 * worst-value statistics come from a sample an order of magnitude larger than minicpm5's
 * (130560 × 87). With the same implementation quality, maxAbs comes out somewhat higher.
 */
const GEMMA4_TOLERANCE: Tolerance = { atol: 1e-2, rtol: 0 };

