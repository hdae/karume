/**
 * One breakdown entry (only the key and the dispatch count — wall time is not this check's
 * concern).
 */
type TimingEntry = { readonly key: string; readonly dispatchCount: number };

const dispatches = (of: readonly TimingEntry[]): number =>
  of.reduce((total, entry) => total + entry.dispatchCount, 0);

/**
 * **Proof that mixed storage actually ran** (ADR 0069 decision 5). The numbers (②) do not tell
 * keys apart — a weight that fell out of eligibility and was expanded to f32 on the CPU gives the
 * same values when implemented correctly. **Only the keys make this distinction**.
 *
 * - The linear family (`linear:` of the default GEMM skeleton and `linear_gemv:` of the GEMV
 *   family — every linear with 1 ≤ M ≤ 64 goes through the latter (ADR 0082), so a short prefill /
 *   decode has only those) all contain `:wi4g32` (i4 group quantization) or `:wi8` (the tied
 *   `lm_head`). If even one bare `linear:v2:f32:…` appears, that weight failed the eligibility
 *   check and was expanded to f32 (the GEMV family opens only on compressed storage).
 * - `embedding:` are all `:wi8` (the main embedding + 35 PLE tables). An i4 execution path exists
 *   for embeddings too, but **this series assigns the embeddings to i8** (the mixed setting in
 *   `gemma4/export.py`) — a `:wi4g32` here means the assignment silently changed.
 * - Both linear variants appearing = the mix itself (one side only would be "uniform storage just
 *   passed").
 */
const assertStorageKeys = (entries: readonly TimingEntry[], shown: string): void => {
  const linear = entries.filter(
    (entry) => entry.key.startsWith("linear:") || entry.key.startsWith("linear_gemv:"),
  );
  assert(linear.length > 0, `no linear breakdown (breakdown that ran: ${shown})`);
  assertEquals(
    linear
      .filter((entry) => !entry.key.includes(":wi4g32") && !entry.key.includes(":wi8"))
      .map((entry) => entry.key),
    [],
    `a linear without compressed storage ran (a weight expanded to f32 after failing eligibility — breakdown that ran: ${shown})`,
  );
  assert(
    linear.some((entry) => entry.key.includes(":wi4g32")) &&
      linear.some((entry) => entry.key.includes(":wi8")),
    `only one kind of linear storage ran (not mixed — breakdown that ran: ${shown})`,
  );

  const embedding = entries.filter((entry) => entry.key.startsWith("embedding:"));
  assert(embedding.length > 0, `no embedding breakdown (breakdown that ran: ${shown})`);
  assertEquals(
    embedding.filter((entry) => !entry.key.includes(":wi8")).map((entry) => entry.key),
    [],
    `an embedding without i8 storage ran (breakdown that ran: ${shown})`,
  );
};

/**
 * ④ Census (ADR 0058 decision 4 / 0067 acceptance condition ③ / 0069 decision 5). Checks from the
 * pipeline-key side that the real model's 35 `attention` nodes **all ran on GQA-variant
 * pipelines** and that linear / embedding **ran on compressed storage as is**.
 *
 * MUST: the source is `lastRunPipelines`, which does not depend on timing (it works on a device
 * without timing). undefined / empty is failed by `requireCensus` in
 * tests/helpers/pipeline-census.ts (no vacuous green).
 */
test.skipIf(!AVAILABLE || !GPU_AVAILABLE)(
  `Gemma 4 E2B census: 35 MQA attentions and the mixed-storage keys (real GPU)${SERIES_CHECKS_OPT_IN}`,
  async () => {
    const parsed = prepareContainer(
      await openSeriesContainer(new URL(MODEL_FILE, SERIES_ROOT)),
      GRAPH_NAME,
    );
    const layers = assertGemma4Form(parsed);

    const gpu = await acquireGpu();
    // MUST: destroying the device also covers a failure of `createSession`. If missed, the rest of
    // that run proceeds holding an undestroyed device and later tests go red with OOM (the deferred
    // release in known-issues).
    try {
      const session = await parsed.createContainerSession(gpu);
      try {
        // The mixed-storage residency itself (ADR 0069's acceptance condition — a measured line
        // independent of the key check). Falling out of eligibility raises no exception and is
        // only expanded to f32 on the CPU, so hostExpandedBytes is the only direct observation.
        const storage = session.diagnostics().storage;
        assert(storage !== undefined, "diagnostics.storage is missing");
        assertEquals(
          storage.hostExpandedBytes,
          0,
          "hostExpandedBytes (CPU expansion after failing eligibility)",
        );
        assert(
          storage.residentCompressedBytes > 3_000_000_000,
          `residentCompressedBytes ${storage.residentCompressedBytes} is not the size of a mixed residency`,
        );

        // The shortest case (T=6) alone is enough — what is looked at is the kinds and counts of
        // the pipelines that ran.
        const { inputs } = await loadCase("capital-en", parsed.graph.inputs);
        await session.run(inputs);
        const entries = requireCensus(session.diagnostics().lastRunPipelines, "capital-en");
        const shown = entries.map((entry) => `${entry.key}×${entry.dispatchCount}`).join(" / ");

        // ①QK and ③PV (②stats are row statistics without a GQA axis, so they are out of scope —
        // their keys carry no `:gqa` either)
        const qk = entries.filter((entry) => entry.key.startsWith("attention_qk"));
        const pv = entries.filter((entry) => entry.key.startsWith("attention_pv"));
        assert(qk.length > 0 && pv.length > 0, `no attention breakdown: ${entries.length} entries`);
        assertEquals(
          [...qk, ...pv].filter((entry) => !entry.key.endsWith(":gqa")).map((entry) => entry.key),
          [],
          `a non-GQA key ran although this is 8:1 MQA (breakdown that ran: ${shown})`,
        );

        // Dispatched for every layer (the 35 layers share one kind of pipeline, so the measurement
        // is 35 each. Row-block splitting (ADR 0060 / 0067 decision 7) would increase it if it
        // came to the storage path, so a lower bound is checked).
        assert(
          dispatches(qk) >= layers && dispatches(pv) >= layers,
          `attention dispatches fall short of the layer count ${layers}: ` +
            `①QK ${dispatches(qk)} / ③PV ${dispatches(pv)}`,
        );

        assertStorageKeys(entries, shown);
        console.log(
          `[e2e] gemma4 1-shot census: QK ${dispatches(qk)} / PV ${dispatches(pv)} / ` +
            `linear ${dispatches(entries.filter((entry) => entry.key.startsWith("linear:")))} / ` +
            `embedding ${dispatches(
              entries.filter((entry) => entry.key.startsWith("embedding:")),
            )}`,
        );
      } finally {
        await session.dispose();
      }
    } finally {
      gpu.destroy();
    }
  },
);

