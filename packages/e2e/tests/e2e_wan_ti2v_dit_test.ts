const GIB = 2 ** 30;
const MIB = 2 ** 20;

/**
 * The DiT layer count of Wan2.2 TI2V-5B (the transformer config's `num_layers`) — the multiplier of the expected ①QK
 * dispatch count.
 */
const DIT_LAYERS = 30;
/** The cross-attention keys (the text token count — `[1,512,4096]` of `encoder_hidden_states`). */
const TEXT_TOKENS = 512;

/**
 * The storage width of one element of S per preset (reference preset = the default f32, practical preset = s16). The
 * practical preset's bundle declares `attentionScoreStorage: "f16"`, and every Wan2.2 shape (D = 128, key counts S and
 * 512) is a multiple of 4 and eligible for s16 (the full-eligibility check pins the path — the eligibility rule is not
 * copied here).
 */
const SEAT_SCORE_BYTES: Readonly<Record<Seat, number>> = {
  [REFERENCE_QUANT]: 4,
  [PRACTICAL_QUANT]: 2,
};

/**
 * The expected number of row blocks (ADR 0124 — per self / cross with the preset's storage width; derived
 * independently of the runtime):
 *
 *   limit = min(binding limit, budget), rows per block = ⌊limit ÷ (heads × keys × storage width)⌋,
 *   blocks = ⌈S ÷ rows per block⌉
 *
 * The key count is S for self and 512 for cross. Only shapes whose score row is larger than the row statistics (2 words
 * = 8 B) are handled, so the row-statistics term has no effect. {@link expectedRowBlocks} is the earlier formula
 * limited to self, f32 and no budget, and is not used for budgeted shapes.
 */
const expectedAttentionBlocks = (
  queries: number,
  keys: number,
  scoreBytes: number,
  bindingLimit: number,
  budget?: number,
): number => {
  const limit = budget === undefined ? bindingLimit : Math.min(bindingLimit, budget);
  return Math.ceil(queries / Math.floor(limit / (WAN22_HEADS * keys * scoreBytes)));
};

/** The ①QK dispatch counts (with the row window `:rwa` and without a row window). */
type QkDispatches = { readonly windowed: number; readonly unwindowed: number };

/**
 * The expected ①QK dispatch counts (30 layers × self / cross). A single-block shape raises no row window and has one
 * dispatch per layer; a shape with two or more blocks has as many per layer under the row-window key.
 */
const expectedQkDispatches = (blocks: { readonly self: number; readonly cross: number }) => {
  const counts = [blocks.self, blocks.cross];
  return {
    windowed:
      DIT_LAYERS * counts.filter((count) => count > 1).reduce((sum, count) => sum + count, 0),
    unwindowed: DIT_LAYERS * counts.filter((count) => count === 1).length,
  } satisfies QkDispatches;
};

