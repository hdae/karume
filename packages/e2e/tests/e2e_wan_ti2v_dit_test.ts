const f32Tensor = (shape: readonly number[], data: Float32Array<ArrayBuffer>): Tensor => ({
  dtype: "f32",
  shape,
  data,
});

const boolTensor = (shape: readonly number[], data: Uint32Array<ArrayBuffer>): Tensor => ({
  dtype: "bool",
  shape,
  data,
});

/**
 * The graph inputs (`input.*` of the io — the declared names, dtypes and shapes as they are; the condition mask is
 * bool = u32 0 / 1).
 */
const graphInputs = (
  golden: Ti2vGolden,
  inputs: readonly { readonly name: string; readonly dtype: string }[],
  where: string,
): Record<string, Tensor> =>
  Object.fromEntries(
    inputs.map(({ name, dtype }) => {
      const key = `input.${name}`;
      const view = viewOf(golden.io, key, where);
      if (dtype === "bool") {
        if (view.dtype !== "U32") {
          throw new Error(`${where}: '${key}' is ${view.dtype} (expected U32)`);
        }
        return [
          name,
          boolTensor(
            view.shape,
            new Uint32Array(golden.io.buffer, view.byteOffset, view.byteLength / 4),
          ),
        ];
      }
      if (dtype !== "f32")
        throw new Error(`${where}: input '${name}' has unexpected dtype ${dtype}`);
      return [name, f32Tensor(view.shape, floatsOf(golden.io, key, where))];
    }),
  );

/** One input (a name the declaration must have — fails when it is missing). */
const inputOf = (inputs: Readonly<Record<string, Tensor>>, name: string): Tensor => {
  const tensor = inputs[name];
  if (tensor === undefined) throw new Error(`graph input '${name}' is missing`);
  return tensor;
};

/** The width of the timestep input (the static dimension of `timesteps_proj` — 256 is not hard-coded). */
