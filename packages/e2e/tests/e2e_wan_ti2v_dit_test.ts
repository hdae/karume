/** The result of one fault injection (the caller judges after all ratios are in). */
type FaultResult = { readonly label: string; readonly ratio: number; readonly note: string };

/** The fault-injection labels (the four of stage 2 of ADR 0121's acceptance — module doc "Fault injection"). */
const TIMESTEP_OFF_BY_ONE = "timestep +1";
const MASK_SHIFT = "condition mask shifted by one token";
const TIME_INPUTS_SWAP = "the two timestep inputs swapped";
const SCALE_FAULT = `${SCALE_FAULT_WEIGHT} scale × 2`;

/**
 * The fault injections run on the same Session (T2V only timestep +1; I2V also the mask shift and the timestep-input
 * swap).
 */
const sessionFaultLabels = (form: Ti2vForm): readonly string[] =>
  form === "i2v" ? [TIMESTEP_OFF_BY_ONE, MASK_SHIFT, TIME_INPUTS_SWAP] : [TIMESTEP_OFF_BY_ONE];

/**
 * The fault injections of an acceptance case that run on the same Session with replaced inputs (scale × 2 uses a
 * separate Session — {@link scaleFault}).
 */
const faultInjections = async (
  golden: Ti2vGolden,
  inputs: Readonly<Record<string, Tensor>>,
  grid: WanTokenGrid,
  form: Ti2vForm,
  expected: Float32Array,
  run: (inputs: Record<string, Tensor>, label: string) => Promise<Float32Array<ArrayBuffer>>,
): Promise<FaultResult[]> => {
  const faults: FaultResult[] = [];
  const measure = async (label: string, faulty: Record<string, Tensor>): Promise<void> => {
    const tokens = await run(faulty, `fault injection ${label}`);
    const diff = difference(unpatchifyTokens(tokens, golden.latentShape, WAN22_GEOMETRY), expected);
    const ratio = ratioOf(diff);
    faults.push({
      label,
      ratio,
      note: `fault injection ${label}: maxAbs ${diff.maxAbs.toExponential(3)} (ratio ${ratio.toExponential(
        2,
      )})`,
    });
  };
  const width = timestepWidth(inputs);
  await measure(TIMESTEP_OFF_BY_ONE, {
    ...inputs,
    timesteps_proj: f32Tensor([1, width], timestepsProj(golden.timestep + 1, width)),
  });
  if (form === "i2v") {
    // Only the first latent frame is the condition — with F' = 1 every token is the condition and there is nowhere to
    // shift to.
    assert(
      grid.frames >= 2,
      `the I2V acceptance case has ${grid.frames} latent frames (expected 2 or more)`,
    );
    const shifted = new Uint32Array(grid.count);
    shifted.fill(1, 1, grid.rows * grid.cols + 1);
    await measure(MASK_SHIFT, {
      ...inputs,
      condition_mask: boolTensor(inputOf(inputs, "condition_mask").shape, shifted),
    });
    await measure(TIME_INPUTS_SWAP, {
      ...inputs,
      timesteps_proj: inputOf(inputs, "timesteps_proj_condition"),
      timesteps_proj_condition: inputOf(inputs, "timesteps_proj"),
    });
  }
  assertEquals(
    faults.map(({ label }) => label),
    [...sessionFaultLabels(form)],
    "the set of fault injections (never shrunk silently)",
  );
  return faults;
};

