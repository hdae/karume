/**
 * The **port check** of Wan2.2 TI2V-5B's DiT (the I2V-capable S-shaped graph, i8 series) (real GPU, ADR 0121 stage 2 —
 * decisions 2 / 4 / 5 / 8).
 *
 * The reference preset `f16+dit8` (int8 weights, f32 compute, empty `session`) runs the int8 transformer of the
 * distribution mirror `models/karume-wan2.2/` (through its manifest — ADR 0139 decision 1), and the latents after the
 * host unpatchify (`src/wan/dit-tokens.ts` — 2.1's function as is, also for 48 latent channels) are compared with the
 * upstream CPU reference taken with the same int8 fake-quantized weights (`output.f64` (activations also f64) and
 * `output` (f32) of `reference.<case>`, a golden of the test-asset root — decision 2; the timestep in decision 4's form:
 * T2V through the 1-D timestep path, I2V through the reference wrapper that runs the timestep MLP per value with
 * M = 1). The precedent is Wan2.1's DiT e2e (`e2e_wan_dit_test.ts`), and the metric, the band derivation, the fault
 * injection, the 1-submit check and the shape of the allocation record follow it.
 *
 * The goldens are generated by `tools/export-recipes/wan/ti2v_export_dit.py` (S = 192 with `write`, full size with
 * `write-full` — the content and the case table are in the docstring of the same file; the TS-side table is
 * `helpers/wan-ti2v-dit.ts`). The patched eager model is bit-identical to upstream in every case (the writer's eager
 * equivalence check — a failing case does not become a golden), so the difference seen here is directly the difference
 * between "the IR run on the GPU" and "upstream".
 *
 * ## Metric and band (decision 5 — the r check of ADR 0118 decision 8 and ADR 0120 decision 3)
 *
 *   r = (max|GPU − f64| ÷ max|f64|) ÷ (max|CPU f32 − f64| ÷ max|f64|)
 *
 * = how many times the GPU error is the error the CPU f32 reference itself makes on the same input
 * ({@link normalizedRatio}). The band is derived independently per group, as the worst r × 5 over that group's six
 * deciding cases (fixed at 3 T2V + 3 I2V) (no band is carried over between groups or from 2.1):
 *
 * - **The S = 192 group** ({@link SMALL_BAND} — 6 deciding cases; acceptance T2V 2 + I2V 2)
 * - **The full-size group** ({@link FULL_BAND} — two shapes = latents `[48,21,30,52]` (S = 8,190) and `[48,9,44,80]`
 *   (S = 7,920). 3 deciding cases per shape, 6 over both shapes; acceptance T2V 2 + I2V 2 per shape, 8 in all). The two
 *   shapes differ in S by only 3% (ADR 0121 addendum "settling ruling 1" — two splits of the token-count budget that
 *   fits on the development machine), so there is one band, and the worst per shape is recorded too
 *   ({@link recordWorst}).
 *
 * `undefined` = not derived yet: each case prints its r and stops red, and the group's last step prints the band
 * candidate (the worst deciding r × 5) ({@link bandCandidate} — no placeholder value that passes and so makes a check
 * without detection power). The value the first real run derived is written into the constant together with the table
 * of measurements.
 * MUST: do not change the band, the deciding cases or the metric after seeing the acceptance results. If an acceptance
 * case leaves the band, investigate the cause instead of widening the band.
 *
 * ## Fault injection (the four of stage 2 of ADR 0121's acceptance — on the acceptance cases; each must fall outside
 * the band)
 *
 * - **timestep +1** (the generated side's `timesteps_proj` built with t + 1): T2V and I2V. A subtle injection, so it
 *   must also stay at least {@link SUBTLE_FAULT_MARGIN} × the band away (detecting a band that is too wide — the same
 *   floor of 2 as 2.1)
 * - **`to_v`'s per-channel scale × 2** ({@link SCALE_FAULT_WEIGHT} — the copy of the scale doubled at the container's
 *   read surface, a separate Session): T2V and I2V
 * - **The condition mask shifted by one token** (the true range moved from the first P tokens to 1..P): I2V only
 * - **The two timestep inputs swapped** (`timesteps_proj` and `timesteps_proj_condition` exchanged): I2V only
 *
 * In T2V the two timestep inputs have the same value and the mask is all false, so the last two cannot show in the
 * values by construction (stage 2 of ADR 0121's acceptance).
 *
 * The acceptance cases also check that they stay inside the band with the product path's inputs (the host's two
 * `timesteps_proj` and the host condition mask in the test — `conditionMask` of `helpers/wan-ti2v-dit.ts`).
 *
 * ## Full-size measurement and records (stage 2 of ADR 0121's acceptance)
 *
 * - The comparison in **measuring mode** (`gpuTiming`): the Session is rebuilt per S (the backings of the two S are
 *   not loaded at once), and the checks are the number of row blocks (the expectation derived from the device's binding
 *   limit — {@link expectedRowBlocks}; on B570, 3 f32 blocks for both S = 8,190 and 7,920) and the maximum GPU time per
 *   submit ≤ {@link SUBMIT_GPU_LIMIT_MS} (including the chunks of the first run before it is backed).
 * - **Normal mode** (no measuring): per S it records the time (wall clock), the diag (the allocations alive right after
 *   the run = weights + that run's arena + slot backing — the same quantity as 2.1's "diagnostic allocation") and the
 *   VRAM peak from fdinfo, and the check is that the output equals the same case in measuring mode as Uint32. The diag
 *   is put next to the capacity threshold {@link DIAG_THRESHOLD_BYTES} (decision 8), and at S = 8,190 its difference
 *   from the extrapolation of the capacity table (a 2.1-type graph — {@link EXTRAPOLATED_DIAG_GIB}) is recorded next to
 *   the expected increase for I2V support (decision 3's +0.19 / worst case +0.56 GiB). Exceeding the threshold does not
 *   turn it red (the move when it is exceeded — lowering the accepted maximum frame count — is a ruling to make before
 *   stage 6; failing here would not fix it). A run that exceeds it prints a warning and writes "exceeded" in the
 *   record.
 * - **The practical preset's 1-submit GPU time** (stage 7 of ADR 0121's acceptance — for 2.1 it is ADR 0120 stage 4):
 *   riding on the measuring-mode comparison, per S, after the reference preset's Session is disposed the practical
 *   preset's Session is built, two runs go with the same input, and the check is the maximum GPU time per submit
 *   ≤ {@link SUBMIT_GPU_LIMIT_MS} ({@link practicalSubmitGate} — the reason for two runs is there). No numeric band is
 *   applied. That the bundle reached the Session is checked in the second run's census. The longest point of ADR 0120
 *   decision 4's form (two points, the default and the longest) is **S = 27,280** (1280×704, 121 frames — the accepted
 *   maximum, the same shape as the opt-in point of the self A/B check); it has no golden, so its input is a random
 *   latent and a real prompt's embedding, and the same check runs in a separate Deno.test. The allocations are large
 *   and it takes long, so it is opt-in (`KARUME_WAN_TI2V_121F=1` — the same variable as the self A/B check and the
 *   end-to-end e2e's 121 frames) and runs as a separate process with `--filter "27280"` (taking a single device — the
 *   same rule as the end-to-end e2e's opt-in). There is an estimate (ADR 0121) that the 16-dispatch chunks before
 *   backing swell on the large-S side, and the 1 s check is most likely to turn red at that point, so the longest point
 *   is not left out.
 *
 * ## Row-block budget (ADR 0124 — `SessionOptions.attentionRowBlockMaxBytes`)
 *
 * - **Layer-1 check (u32 A/B)**: with the same input (a random latent, fixed seed), no budget / 512 MiB / 256 MiB run
 *   per Session, and the output must equal the no-budget output as Uint32. It runs for both presets (reference and
 *   practical). The shapes are 1280×704×17 (S = 4,400, default lane) and 1280×704×121 (S = 27,280, opt-in
 *   `KARUME_WAN_TI2V_121F=1`, separate process). Against vacuity it also checks at the same time that the ①QK dispatch
 *   counts (row window `:rwa` and the rest) match the expected block counts per self / cross with the preset's storage
 *   width ({@link expectedAttentionBlocks} — derived independently of the runtime) and differ from the no-budget run.
 *
 * Environments without the assets and environments without a GPU **SKIP explicitly** with the generation command (ADR
 * 0005). Golden completeness (an environment with only some of them FAILs) is checked per group by the GPU-free host
 * test (`wan_ti2v_dit_host_test.ts`).
 *
 * ## Default run and opt-in upstream parity (maintainer ruling 2026-10-17)
 *
 * Every comparison with the diffusers reference (the r gates of the S = 192 and full-size groups,
 * the normal-mode r check, and the fault injections that prove those bands are live) is opt-in
 * behind `KARUME_UPSTREAM_PARITY=1` (`helpers/upstream-parity.ts`). The default run keeps the checks
 * that do not read the f64 reference: non-finite 0, the fusion counts, the golden S and the
 * row-block count, the 1-submit GPU time gates of both seats, the normal-mode Uint32 identity with
 * the measured mode, and the row-block budget u32 A/B.
 */

