/**
 * Turns the same text as the reference WAV into an utterance (caller-side analysis — every check
 * uses the same one).
 *
 * MUST: analyze only once. Do not repeat the dictionary fetch (network on the first run only) per
 * check.
 */
const utteranceOnce = (() => {
  let cached: Promise<Utterance> | undefined;
  return (): Promise<Utterance> => {
    // TypeScript 7 does not narrow `cached` after `??=`; keep the single-evaluation semantics explicitly.
    const utterance =
      cached ??
      getDictionary().then((dictionary) => toUtterance(analyzeWithWords(dictionary, TEXT)));
    cached = utterance;
    return utterance;
  };
})();

const sha256Hex = async (bytes: Uint8Array<ArrayBuffer>): Promise<string> =>
  Array.from(new Uint8Array(await crypto.subtle.digest("SHA-256", bytes)))
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");

const readManifest = (): Manifest => parseManifest(manifestText as string);

const modelEntry = (manifest: Manifest, model: string = MODEL): ModelEntry => {
  if (!Object.hasOwn(manifest.models, model)) {
    throw new Error(
      `the distribution has no model '${model}' (present: ${manifest.available.models.join(" / ")})`,
    );
  }
  return manifest.models[model];
};

/**
 * Reads the assets the given model / quant requires from local files (a local version of
 * `fetchAssets` — a path that bypasses the fetch layer, so the check covers the pipeline alone).
 * Keys pointing at the same path are read once.
 */
const loadLocalAssets = async (
  manifest: Manifest,
  quant: string = QUANT,
  model: string = MODEL,
): Promise<Record<string, Uint8Array<ArrayBuffer>>> => {
  const selection = resolveSelection(manifest, { model, quant });
  const byPath = new Map<string, Uint8Array<ArrayBuffer>>();
  let assets: Record<string, Uint8Array<ArrayBuffer>> = {};
  const read = async (key: string, ref: FileRef): Promise<void> => {
    const cached = byPath.get(ref.path);
    const bytes = cached ?? (await readFile(new URL(ref.path, ASSETS_DIR)));
    if (cached === undefined) byPath.set(ref.path, bytes);
    assets = { ...assets, [key]: bytes };
  };
  // MUST: zero-length parts are listed too (the index is the id inside the container — skipping
  // one would shift every later one up by one).
  for (const name of Object.keys(selection.containers)) {
    const { parts } = selection.containers[name];
    for (const [index, ref] of parts.entries()) await read(`${name}[${index}]`, ref);
  }
  for (const name of Object.keys(selection.assets)) await read(name, selection.assets[name]);
  return assets;
};

/**
 * Checks the check's **preconditions** (not the check itself). The reference WAV was baked with
 * the distribution's default knobs, so a distribution whose defaults moved fails with "the
 * conditions differ" rather than "the sha256 differs". Only the speaker differs per model (jvnv is
 * one speaker per model), so it is taken as an argument.
 */
const assertReferenceKnobs = (
  entry: ModelEntry,
  speaker: string = REFERENCE_KNOBS.speaker,
): Sbv2Defaults => {
  const { defaults } = parseSbv2PipelineConfig(entry.pipelineConfig);
  const expected: Sbv2Defaults = { ...REFERENCE_KNOBS, speaker };
  const drifted = KNOB_KEYS.filter((key) => defaults[key] !== expected[key]);
  if (drifted.length > 0) {
    throw new Error(
      `the distribution's pipelineConfig.defaults differ from the reference WAV's generation conditions: ` +
        drifted.map((key) => `${key} ${expected[key]} → ${defaults[key]}`).join(" / ") +
        " (the check's preconditions broke — find out why the conditions changed first, instead of replacing the reference sha256)",
    );
  }
  return defaults;
};

/**
 * A one-line rendering of the effective knobs (keeps "what was baked" in the report when the
 * comparison breaks). The check passes no knob to `generate`, so the distribution's defaults = the
 * effective values.
 */
const describeKnobs = (
  defaults: Sbv2Defaults,
  quant: string = QUANT,
  model: string = MODEL,
): string =>
  `model ${model} / quant ${quant} / seed ${SEED} / text ${JSON.stringify(TEXT)} / ` +
  KNOB_KEYS.map((key) => `${key} ${defaults[key]}`).join(" / ") +
  ` / yomi ${YOMI_VERSION}`;

/**
 * If the reference WAV file is at hand, prints **the first differing position** too (material for
 * the F1 / `i8` check only).
 *
 * MUST: check the file's sha256 before using it — diffing against a WAV baked under other
 * conditions would make the diagnosis itself a lie.
 */
const describeFirstDifference = async (
  expected: string,
  actual: Uint8Array<ArrayBuffer>,
): Promise<string> => {
  const reference = await readFileIfPresent(REFERENCE_WAV);
  if (reference === undefined) {
    return `no reference WAV file (${REFERENCE_WAV.pathname}) — the first differing position cannot be shown`;
  }
  const sha = await sha256Hex(reference);
  if (sha !== expected) {
    return `${REFERENCE_WAV.pathname} is not the reference WAV (sha256 ${sha}) — the first differing position cannot be shown`;
  }
  const shared = Math.min(reference.length, actual.length);
  let at = 0;
  while (at < shared && reference[at] === actual[at]) at += 1;
  if (at === shared) {
    return `the first ${shared} bytes match (only the length differs: reference ${reference.length} / measured ${actual.length})`;
  }
  const header = 44;
  const where =
    at < header
      ? `inside the RIFF header (offset ${at})`
      : `sample ${Math.floor((at - header) / 2)} (offset ${at})`;
  const view = (bytes: Uint8Array): number =>
    new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getInt16(
      header + Math.floor((at - header) / 2) * 2,
      true,
    );
  const values =
    at < header
      ? `byte ${reference[at]} → ${actual[at]}`
      : `i16 ${view(reference)} → ${view(actual)}`;
  return `the first difference is at ${where}: ${values}`;
};

/**
 * The report when the reference sha disagrees (shared by every check).
 *
 * MUST: do not escape into a tolerance here. The artifact stays in the results slot
 * (`outputs/verify/...`), in a form a person can listen to and compare.
 */
const mismatchReport = async (
  audio: GeneratedAudio,
  wav: Uint8Array<ArrayBuffer>,
  actual: string,
  expected: string,
  defaults: Sbv2Defaults,
  quant: string,
  model: string,
  dumped: URL,
): Promise<string> => {
  // The material for the first differing position (the frozen reference WAV file) exists only
  // for F1 / i8.
  const difference =
    model === MODEL && quant === QUANT ? `\n  ${await describeFirstDifference(expected, wav)}` : "";
  return (
    `the output WAV's sha256 does not match the reference\n` +
    `  expected ${expected}\n  actual ${actual}\n` +
    `  WAV ${wav.length} bytes / samples ${audio.data.length} / ${audio.sampleRate}Hz / ` +
    `${(audio.data.length / audio.sampleRate).toFixed(3)}s\n` +
    `  effective knobs ${describeKnobs(defaults, quant, model)}${difference}\n` +
    `  artifact ${dumped.pathname}`
  );
};

/**
 * Keeps the artifact, compares it with the reference value, and adds the verdict to the results
 * JSON (the shared tail of every check).
 *
 * The artifact is written **every time, pass or fail** — the A/B material for the next break is
 * needed before it breaks.
 */
const settleCase = async (
  audio: GeneratedAudio,
  wav: Uint8Array<ArrayBuffer>,
  actual: string,
  defaults: Sbv2Defaults,
  elapsedMs: number,
  quant: string = QUANT,
  model: string = MODEL,
): Promise<void> => {
  // This path may write reference values, so first check that the adapter the key was taken from
  // is the one running.
  await assertRunningAdapter();
  const caseId = caseIdOf(model, quant);
  const artifact = `${caseId}.wav`;
  const dumped = results.artifact(artifact);
  await writeFile(dumped, wav);
  const check = references.check(caseId, actual);
  announceCheck(caseId, check, actual);
  const expected = expectedOf(check);
  await results.record({
    id: caseId,
    status: check.status,
    ...(expected === undefined ? {} : { expected }),
    actual,
    artifact,
    elapsedMs,
  });
  if (check.status === "fail") {
    throw new Error(
      await mismatchReport(audio, wav, actual, check.expected, defaults, quant, model, dumped),
    );
  }
};

/**
 * Checks "it does not collide with another quant's reference value" (detecting a quant that did
 * not take effect).
 *
 * NOTE: if this environment does not have the counterpart's row yet, the check does not hold
 * (when every case is run through with `write`, the rows of the quants registered earlier always
 * exist).
 */
const assertNoCollision = (
  actual: string,
  label: string,
  others: readonly { readonly caseId: string; readonly why: string }[],
): void => {
  for (const other of others) {
    if (references.lookup(other.caseId) === actual) {
      throw new Error(
        `${label}'s WAV matched ${other.caseId} exactly by sha256 (${actual}) — ${other.why}`,
      );
    }
  }
};

test.skipIf(!RUNNABLE || references.lacksReference(caseIdOf(MODEL, QUANT)))(
  `e2e (real GPU): the WAV of distribution ${MODEL} / quant ${QUANT} / seed ${SEED} matches the reference sha256`,
  async () => {
    const manifest = readManifest();
    const defaults = assertReferenceKnobs(modelEntry(manifest));
    const assets = await loadLocalAssets(manifest);
    const started = performance.now();
    // `await using` also intends to check the release through [Symbol.asyncDispose] on this
    // real-GPU path.
    await using pipeline = await Pipeline.fromAssets(
      { manifest, assets },
      {
        model: MODEL,
        quant: QUANT,
      },
    );
    // Pass no knob — let `pipelineConfig.defaults` fill them, as for the reference WAV.
    const audio = await pipeline.generate(await utteranceOnce(), { seed: SEED });
    const wav = encodeWav(audio.data, audio.sampleRate);
    const actual = await sha256Hex(wav);
    const elapsedMs = performance.now() - started;
    console.log(
      `[e2e] sbv2 ${MODEL}/${QUANT}: ${(elapsedMs / 1000).toFixed(1)}s / WAV ${wav.length}B / ` +
        `${(audio.data.length / audio.sampleRate).toFixed(2)}s / yomi ${YOMI_VERSION} / ` +
        `sha256 ${actual}`,
    );
    await settleCase(audio, wav, actual, defaults, elapsedMs);
  },
);

