/**
 * SBV2's **regression check** (real GPU). It goes all the way from the distribution through
 * `Pipeline.fromAssets` → `generate` → `encodeWav` and looks only at whether the output WAV's
 * sha256 is **bit-identical** to the reference value (the audio version of the same philosophy as
 * Anima's PNG check `e2e_anima_test.ts`).
 *
 * **The proof of port identity** — "the WAV of the distribution + `i8` matches the stage-1 path
 * (reading `outputs/series/` directly) exactly by sha256" — **was done in the FN4 era** (the
 * measurement in the Consequences section of ADR
 * [0039](../../../docs/decisions/0039-sbv2-distribution.md)). What this check holds back is **the
 * regressions since then**.
 *
 * **If a value moves by even one bit, something in the port changed — switching to a tolerance is
 * forbidden**: stop red and print what differs (WAV byte length / sample count / effective knobs /
 * the WAV itself). Loosening this would erase the meaning of "the port works".
 *
 * ## Generation conditions of the reference values (the RTX 3080 Ti row frozen on 2026-08-30)
 *
 * - **The assets are `models/karume-sbv2-jvnv/`** — the public mirror whose license and attribution
 *   are correct. By the ruling of 2026-08-30 the check was moved off the old one, whose source of
 *   truth was a private FN mirror (the FN4-era reference values and the re-takes are in the git
 *   history). The reference values were taken and frozen in that reference environment, and a
 *   person listened at freeze time to confirm they are sound (the procedure is the manual check of
 *   the completion report — a sha alone does not guarantee "the right sound").
 * - **The text is `DEFAULT_TEXT` of `examples/sbv2/main.ts`, seed 0** (unchanged since the FN4
 *   era).
 * - **style / speaker / styleWeight / the 4 knobs are the manifest's `pipelineConfig.defaults`**.
 *   The check passes no knob to `generate`, so the effective values are the distribution's defaults
 *   as is. The effective values are copied into {@link REFERENCE_KNOBS}, and **a change of the
 *   distribution's defaults fails before the check** (so "a numerical regression" is not confused
 *   with "replaced assets").
 * - **Model axis**: the 3 quant discriminations (`i8` / `i8+bert4` / `i4`) are closed on F1
 *   (defaultModel), and F2 / M1 / M2 get one `i8` each — a pin that asset resolution did not fall
 *   to another model (an axis the old check lacked. net_g's real weights differ per model, so
 *   matching F1 means the resolution broke).
 *
 * ## The second check — `i8+bert4` (BERT's linears baked as mixed i4)
 *
 * The conditions are the same as `i8` (F1 / seed 0 / the distribution's default knobs); only the
 * quant is swapped. **A different value from `i8` is correct**, so matching `i8`'s digest also
 * fails — a match is evidence that "the i4 quant did not take effect" (the quant resolution fell
 * to the default / i8 assets went into the i4 component), which the numerical net does not catch.
 *
 * ## The third check — `i4` (a distribution with all 3 components baked as mixed i4)
 *
 * Again the conditions are the same as `i8`; only the quant is swapped. **A value different from
 * both `i8` and `i8+bert4` is correct**, and matching either fails — a match with `i8+bert4` is
 * evidence that "the i4 components on the net_g side did not take effect", and since net_g has
 * only 6 eligible linears (front 2 / voice 4), **not even the difference in asset size would show
 * it**.
 *
 * ## The reference digests are rows per environment (no bit identity across devices is promised)
 *
 * The reference values are in `fixtures/references/sbv2.json` as **rows per environment key**
 * (`helpers/reference.ts`). The RTX 3080 Ti row was baked in the reference environment (Linux /
 * Vulkan (wgpu)), and not matching on other backends (Metal etc.) is by design. The mechanism and
 * how to check soundness on another backend (self A/B) are in the "sha256 reference checks are
 * specific to the reference environment" section of [limitations](../../../docs/limitations.md).
 *
 * - **Adding another machine's row** is `KARUME_REFERENCE=write` (existing rows are not touched).
 * - **Re-baking your own machine's row** is `KARUME_REFERENCE=rewrite` only, and only once you can
 *   say "what changed" first (old → new goes to the log). Other environments' rows are left alone.
 * - On a machine with no reference value the case **SKIPs explicitly**, and the reference gate (at
 *   the end of this file) reports "all SKIP for lack of references" in red.
 *
 * MUST: the assets are `models/karume-sbv2-jvnv/` (untracked, local assets of a real-GPU machine —
 * generated by `dist.py`, docs/assets-layout.md). Environments without them and without a GPU
 * **SKIP explicitly** with a reason (no deleting tests to go silently green — ADR 0005).
 *
 * NOTE: only the tests read local files (`readFile` of `@karume/test-support/fs`). The package
 * itself uses Web standard APIs only (a cross-cutting invariant), and `fromAssets` is a surface that
 * only takes bytes.
 * **Text analysis became the caller's responsibility in 0.6.0**, so it is this test itself that
 * goes out to fetch the Japanese dictionary (`@hdae/yomi` is not a dependency of models; here it is
 * used as "the caller") — the network is needed on the first run only (later runs are served from
 * the Cache API). The dictionary version is also an input that decides the waveform, so the
 * `@hdae/yomi` version goes to the log for when the comparison breaks.
 */

