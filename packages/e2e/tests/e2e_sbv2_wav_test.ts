// --- Serialization and lifetime (concurrent generate / the disposed check) ------
//
// `Pipeline`'s contract is not to keep the 3 graphs (text_encoder / front / voice) resident at
// once, and what upholds it is `generate`'s serialization chain (the MUST in the module doc). Even
// if the implementation regressed to interleaving runs on concurrent calls, **the resulting
// waveform would be correct**, so only the component sequence seen by the observation hook catches
// it. The gemma4 side has a check of the same shape (`e2e_gemma4_chat_test.ts`'s "a disposed
// pipeline does not accept generation").

describe.skipIf(!RUNNABLE)(
  "e2e (real GPU): concurrent generate calls are serialized, and no generation is accepted after dispose",
  () => {
    // Assigned in beforeAll; the its below run sequentially against this one pipeline.
    const seen: string[] = [];
    let pipeline: Pipeline;
    let utterance: Utterance;

    beforeAll(async () => {
      const manifest = readManifest();
      const assets = await loadLocalAssets(manifest);
      pipeline = await Pipeline.fromAssets(
        { manifest, assets },
        {
          model: MODEL,
          quant: QUANT,
          onRunDiagnostics: (component) => seen.push(component),
        },
      );
      utterance = await utteranceOnce();
    });
    // dispose is idempotent; this returns the GPU when the first it below never ran (a failing
    // beforeAll, or a name filter that skips it).
    afterAll(async () => {
      if (pipeline !== undefined) await pipeline.dispose();
    });

    it("issuing 2 at once does not interleave the runs", async () => {
      try {
        // Issue 2 without awaiting (without the chain, the 2nd text_encoder could run before the
        // 1st front).
        await Promise.all([
          pipeline.generate(utterance, { seed: SEED }),
          pipeline.generate(utterance, { seed: SEED }),
        ]);
        assertEquals(seen, ["text_encoder", "front", "voice", "text_encoder", "front", "voice"]);
      } finally {
        // Return the GPU even if the step above fails (the next 2 steps look at the disposed
        // behaviour).
        await pipeline.dispose();
      }
    });

    it("no generation once disposed", async () => {
      await assertRejects(
        () => pipeline.generate(utterance, { seed: SEED }),
        Error,
        "sbv2.Pipeline: cannot generate after dispose",
      );
    });

    it("a second dispose returns the same completion (no early return misread as already disposed)", () => {
      assert(pipeline.dispose() === pipeline.dispose(), "dispose() returned a different Promise");
    });
  },
);

// --- The observation hook (onRunDiagnostics) --------------------------------
//
// Pins that one synthesis = the 3 runs text_encoder → front → voice, each observed once **in this
// order**, with the diagnostics carrying the execution record (dispatch count, the latest run's
// arena record). The check also covers that on a GPU that did not request gpuTiming,
// `lastRunTiming` stays undefined (ADR 0021/0032 — no silent approximation).

test.skipIf(!RUNNABLE)(
  "e2e (real GPU): onRunDiagnostics carries diagnostics with the component name on every run",
  async () => {
    const manifest = readManifest();
    const assets = await loadLocalAssets(manifest);
    const seen: { component: string; dispatches: number; ran: boolean; timed: boolean }[] = [];
    await using pipeline = await Pipeline.fromAssets(
      { manifest, assets },
      {
        model: MODEL,
        quant: QUANT,
        onRunDiagnostics: (component, diagnostics) =>
          seen.push({
            component,
            dispatches: diagnostics.submit.dispatchCount,
            ran: diagnostics.lastRun !== undefined,
            timed: diagnostics.lastRunTiming !== undefined,
          }),
      },
    );
    await pipeline.generate(await utteranceOnce(), { seed: SEED });
    assertEquals(
      seen.map((run) => run.component),
      ["text_encoder", "front", "voice"],
    );
    for (const run of seen) {
      if (run.dispatches <= 0 || !run.ran) {
        throw new Error(
          `${run.component}'s diagnostics do not carry the execution record` +
            `（dispatch ${run.dispatches} / lastRun ${run.ran}）`,
        );
      }
      // The GPU did not request gpuTiming, so having no per-op times is correct (enabling it is
      // the responsibility of whoever passes acquireGpu({ gpuTiming: true }) to options.gpu).
      if (run.timed) {
        throw new Error(`${run.component} returned lastRunTiming on a GPU without timing`);
      }
    }
  },
);

