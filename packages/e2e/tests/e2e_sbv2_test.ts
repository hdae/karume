/**
 * Lists an asset directory. Only a missing directory degrades to empty.
 * MUST: anything other than NotFound propagates — reading a permission error or the like as "no
 * asset" would quietly turn a check that never ran green as a SKIP.
 */
const listDir = (url: URL): readonly DirEntry[] => {
  try {
    return [...readDirSync(url)];
  } catch (cause) {
    if (isNotFound(cause)) {
      return [];
    }
    throw cause;
  }
};

type Sbv2Case = {
  readonly target: string;
  readonly caseName: string;
  readonly ioFile: string;
};

/**
 * Enumerated synchronously, as registration needs it (the same reason as Deno.test's ignore). The
 * raw weights (config.json / ckpt / style_vectors.npy) live separately under `inputs/sbv2/F1/` and
 * do not come into the series root, but a target is a directory, so looking at **directories
 * only** is kept.
 */
const discoverTargets = (root: URL): readonly string[] =>
  listDir(root)
    .filter((entry) => entry.isDirectory)
    .map((entry) => entry.name)
    .sort();

const discoverCases = (root: URL, target: string): readonly Sbv2Case[] =>
  listDir(new URL(`${target}/`, root))
    .filter(
      (entry) => entry.isFile && entry.name.startsWith(IO_PREFIX) && entry.name.endsWith(IO_SUFFIX),
    )
    .map((entry) => ({
      target,
      caseName: entry.name.slice(IO_PREFIX.length, entry.name.length - IO_SUFFIX.length),
      ioFile: entry.name,
    }))
    .sort((a, b) => a.caseName.localeCompare(b.caseName));

const readBuffer = async (root: URL, target: string, file: string): Promise<ArrayBuffer> => {
  const bytes = await readFile(new URL(`${target}/${file}`, root));
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
};

