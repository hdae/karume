/**
 * Loads one golden case, runs it on the GPU and asserts everything except the tolerance
 * comparison (tolerance table length, storage dtype set, io keys, output keys / shape / dtype).
 * Both the default structure case and the opt-in parity case go through here, so the parity case
 * keeps every assertion it had before the split.
 */
const runGoldenCase = async (
  series: Sbv2Series,
  target: string,
  caseName: string,
  ioFile: string,
) => {
  const source = sourceOf(series, target);
  const [opened, ioBytes] = await Promise.all([
    openTarget(series, target, source),
    readGolden(source, target, ioFile),
  ]);
  const parsed = prepareContainer(opened, graphOf(series, target, source));
  const io = parseSafetensors(ioBytes);
  // Checked with Object.hasOwn (a bare `tolerances[target]` would pick up keys from the
  // prototype).
  assert(
    Object.hasOwn(series.tolerances, target),
    `the ${series.name} series has no tolerance for ${target}`,
  );
  const tolerances = series.tolerances[target];
  // The value range differs per output (front's logs_p is an order of magnitude smaller than the
  // other 3), so a table with the wrong count would quietly pass by "comparing against another
  // output's threshold".
  assertEquals(
    tolerances.length,
    parsed.graph.outputs.length,
    `${series.name}/${target}: the tolerance count differs from the IR output count`,
  );

  // The storage dtypes of the series and the assets agree (the only detector of a mixed-up root /
  // forgotten compression — the MUST of `compressedStorage` above). Every one of the 5 targets has
  // several eligible slots, so check that "the set of compressed dtypes that appear" equals the
  // series' declaration exactly (a set rather than a count, so the shape of i8 assets mixed into
  // the f16 series does not pass as "at least one compressed").
  // NOTE: `i32` storage (symbol-dependent constants — ADR 0010) is not compression, so it is not
  // counted here.
  const compressed = [
    ...new Set(
      Object.values(parsed.graph.initializers)
        .flatMap((initializer) =>
          initializer.storage === undefined ? [] : [codecLayout(initializer.storage.codec)],
        )
        .filter((layout) => layout === "f16" || layout === "i8"),
    ),
  ].sort();
  assertEquals(
    compressed,
    series.compressedStorage === undefined ? [] : [series.compressedStorage],
    `${series.name}/${target}: the set of compressed storage dtypes disagrees with the series`,
  );
  // NOTE: the existence of i8's companion scale (ADR 0019) is not checked here. In a container the
  // binding table points at the scale by block id, and `openContainer`'s merge layer has already
  // checked it against the table of contents and its length (rows × groups × 4) (container-v1 §5 /
  // §7), so a check looking at the declaration and the data separately would be vacuous. In the
  // old shard form the two were independent, which is why there was a check.

  // Every tensor of io maps exactly onto the graph's inputs and outputs (nothing extra, nothing
  // missing).
  const expectedKeys = [
    ...parsed.graph.inputs.map((spec) => `input.${spec.name}`),
    ...parsed.graph.outputs.map((_, index) => `output.${index}`),
  ].sort();
  assertEquals([...io.tensors.keys()].sort(), expectedKeys, `${ioFile} tensor keys`);

  // The symbolic dimension P is bound from the actual length of the golden's input shape (no
  // explicit bindings are passed). P differs per case (2 / 37 / 203 / 512 / 16), so an
  // implementation that depends on the declared upper bound Pmax = 512 (building the plan with
  // Pmax, etc.) breaks a value or a shape here.
  const inputs: Record<string, Tensor> = {};
  for (const spec of parsed.graph.inputs) {
    const view = io.tensors.get(`input.${spec.name}`);
    assert(view !== undefined, `input.${spec.name} is not in ${ioFile}`);
    inputs[spec.name] = ioTensor(io, view, spec.dtype);
  }

  const gpu = await acquireGpu();
  // MUST: the device is destroyed even when the adapter check or `createSession` fails. Missing
  // that, the rest of the run carries an undestroyed device and later cases go red with OOM (the
  // deferred release in known-issues).
  try {
    // This path keeps the reference values and results as this machine's rows, so check here that
    // the adapter the key was taken from is the one running (mixing them up on a multi-GPU machine
    // would measure against another machine's band).
    assertAdapterMatchesEnvironment(gpu);
    const session = await parsed.createContainerSession(gpu);
    try {
      const outputs = await session.run(inputs);
      assertEquals(Object.keys(outputs).sort(), [...parsed.graph.outputs].sort());

      parsed.graph.outputs.forEach((name, index) => {
        const view = io.tensors.get(`output.${index}`);
        assert(view !== undefined, `output.${index} is not in ${ioFile}`);
        const where = `${series.name}/${target}/${caseName} output.${index} ('${name}')`;
        const declared = parsed.graph.values[name].dtype;
        assertEquals(outputs[name].shape, view.shape, `${where}: shape`);
        assertEquals(outputs[name].dtype, declared, `${where}: dtype`);
      });
      return { parsed, io, outputs, tolerances };
    } finally {
      await session.dispose();
    }
  } finally {
    gpu.destroy();
  }
};

/** The expected cases of a target, registered (and skipped by name) where nothing can be read. */
const expectedCases = (target: string): readonly Sbv2Case[] =>
  EXPECTED_CASES.map((caseName) => ({
    target,
    caseName,
    ioFile: `${IO_PREFIX}${caseName}${IO_SUFFIX}`,
  }));

if (!MIRROR_PRESENT) {
  console.warn(
    `[karume] skipping the SBV2 front / voice cases of the f16 and i8 series: the distribution ` +
      `mirror ${MIRROR_ROOT.pathname} is absent (or not karume/5).`,
  );
}

for (const series of SERIES) {
  /**
   * The implementation-time part: the whole series directory (MUST: listed only under
   * SERIES_CHECKS — the default lanes do not read `outputs/series/`).
   */
  const targets = SERIES_CHECKS ? discoverTargets(series.root) : [];
  /**
   * Whether assets are present. None at all = an environment that did not generate them, so
   * everything SKIPs (a partial gap goes to FAIL).
   */
  const available = targets.length > 0;
  /** The shipped targets of this series, read from the mirror and the test-asset root. */
  const shippedTargets = EXPECTED_TARGETS.filter(
    (target) => sourceOf(series, target).kind === "mirror",
  );
  /** The targets the series cases still read from the series itself (all five for f32). */
  const seriesTargets: readonly string[] = EXPECTED_TARGETS.filter(
    (target) => sourceOf(series, target).kind === "series",
  );
  const goldenRoot = goldenDir(series.directory);
  const shippedCases = shippedTargets.flatMap((target) => discoverCases(goldenRoot, target));
  /** Whether any golden of the shipped targets was fetched (partial presence FAILs below). */
  const goldensPresent = shippedCases.length > 0;

  // Asset-free: runs in every lane (a key without a target, or a target without a key, would
  // compare some target against another one's tolerances).
  test(`SBV2 tolerance table (${series.name}): one entry per expected target`, () => {
    // Tolerances are derived from measurements per target. A hole in the table is the silent
    // error of "comparing with another target's values", so it is closed by equality with the
    // target list (one table per series).
    assertEquals(
      Object.keys(series.tolerances).sort(),
      [...EXPECTED_TARGETS].sort(),
      `the ${series.name} series' tolerance table`,
    );
  });

  if (shippedTargets.length > 0 && !goldensPresent && !FETCHED) {
    console.warn(
      `[karume] skipping the SBV2 ${shippedTargets.join(" / ")} cases (${series.name}): no ` +
        `goldens under ${goldenRoot.pathname}{${shippedTargets.join(",")}}/. Fetch: ${FETCH_COMMAND}`,
    );
  }

  if (SERIES_CHECKS && !available) {
    console.warn(
      `[karume] ${series.root.pathname} has no exported targets, so the real-weight SBV2 E2E ` +
        `(${series.name} series) is SKIPped (outside the repository because the weights are about 251 MB). ` +
        `Generate: ${series.generate}`,
    );
  }

  test.skipIf(!available)(
    `SBV2 assets (${series.name}): the expected targets and cases are present${SERIES_CHECKS_OPT_IN}`,
    () => {
      // Only the targets the series cases read must be present (the shipped front / voice come
      // from the mirror, so the series may have dropped them — ADR 0139 decision 8); a target
      // outside EXPECTED_TARGETS still FAILs, so an export target added without the table does not
      // pass unseen.
      assertEquals(
        targets.filter((target) => seriesTargets.includes(target)),
        seriesTargets,
        `${series.root.pathname}: the targets the series cases read`,
      );
      assertEquals(
        targets.filter((target) => !(EXPECTED_TARGETS as readonly string[]).includes(target)),
        [],
        `${series.root.pathname}: targets outside EXPECTED_TARGETS`,
      );
      // The graph-name table (helpers/series-graphs.ts) is also closed by equality with the target
      // list. A hole would fail loudly right before the comparison, but only after reading a
      // golden, which is late.
      assertEquals(
        Object.keys(seriesComponents(series.directory)).sort(),
        [...EXPECTED_TARGETS].sort(),
        `${series.directory}: graph-name table`,
      );
      for (const target of seriesTargets) {
        assertEquals(
          discoverCases(series.root, target).map((entry) => entry.caseName),
          [...EXPECTED_CASES],
          `${target}: golden cases`,
        );
        assert(modelPresent(modelUrl(series.root, target)), `${target}/${MODEL_FILE} is missing`);
      }
    },
  );

  if (shippedTargets.length > 0) {
    // Runs when any golden is present, or when the fetch is complete (then an absent golden is a
    // file the dataset at the pin lacks — a FAIL, not a SKIP).
    test.skipIf(!goldensPresent && !FETCHED)(
      `SBV2 golden assets (${series.name}): the shipped targets hold the expected cases`,
      () => {
        for (const target of shippedTargets) {
          const where = new URL(`${target}/`, goldenRoot).pathname;
          const found = discoverCases(goldenRoot, target);
          if (FETCHED && found.length === 0) throw missingAtPin(where);
          assertEquals(
            found.map((entry) => entry.caseName),
            [...EXPECTED_CASES],
            `${where}: golden cases${FETCHED ? AT_PIN : ""}`,
          );
        }
      },
    );
  }

  /**
   * Per target: the cases to register and whether they can run. A shipped target needs its
   * goldens and the mirror; any other target is an implementation-time case of the series.
   */
  const plan = EXPECTED_TARGETS.map((target) => {
    if (sourceOf(series, target).kind === "mirror") {
      const present = discoverCases(goldenRoot, target);
      return {
        cases: present.length > 0 ? present : expectedCases(target),
        // Goldens absent from a complete fetch run (and FAIL by name); the mirror's absence SKIPs.
        runnable: (present.length > 0 || FETCHED) && MIRROR_PRESENT,
        suffix: "",
      };
    }
    // Under SERIES_CHECKS the cases on disk (a target missing from the series registers none —
    // the completeness case FAILs it); otherwise the expected set, each skipped by name.
    return {
      cases: SERIES_CHECKS ? discoverCases(series.root, target) : expectedCases(target),
      runnable: available,
      suffix: SERIES_CHECKS_OPT_IN,
    };
  });

  for (const { cases, runnable, suffix } of plan) {
    for (const { target, caseName, ioFile } of cases) {
      /**
       * The case ID (another series / target has the same case names, so it is kept as a
       * tuple).
       */
      const caseId = `${series.name}/${target}/${caseName}`;
      // Default run: everything except the tolerance comparison (tolerance table length, storage
      // dtype set, io key correspondence, output keys / shape / dtype).
      test.skipIf(!runnable || !GPU_AVAILABLE)(
        `SBV2 golden structure: ${series.name} / ${target} / ${caseName} (real GPU / storage dtype, shape, dtype)${suffix}`,
        async () => {
          await runGoldenCase(series, target, caseName, ioFile);
        },
      );
      // Opt-in: the per-output comparison with the torch CPU goldens under the series' tolerance
      // table. The results.json entry keeps the case id `caseId`.
      test.skipIf(!UPSTREAM_PARITY || !runnable || !GPU_AVAILABLE)(
        `SBV2 golden parity: ${series.name} / ${target} / ${caseName} (real GPU / torch CPU golden)${UPSTREAM_PARITY_OPT_IN}${suffix}`,
        async () => {
          await runRecordedCase(results, { id: caseId }, async ({ measurements }) => {
            const { parsed, io, outputs, tolerances } = await runGoldenCase(
              series,
              target,
              caseName,
              ioFile,
            );
            parsed.graph.outputs.forEach((name, index) => {
              const view = io.tensors.get(`output.${index}`);
              assert(view !== undefined, `output.${index} is not in ${ioFile}`);
              const where = `${series.name}/${target}/${caseName} output.${index} ('${name}')`;
              const declared = parsed.graph.values[name].dtype;
              const report = compareTensors(
                outputs[name],
                ioTensor(io, view, declared),
                tolerances[index],
              );
              measurements.push({
                output: name,
                maxAbs: report.maxAbsError,
                maxRel: report.maxRelError,
                tolerance: tolerances[index],
                stage: "karume",
              });
              assert(report.pass, `${where}: ${formatAllclose(report)}`);
            });
          });
        },
      );
    }
  }
}
