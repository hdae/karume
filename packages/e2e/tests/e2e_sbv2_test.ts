// Real-weight golden E2E of the SBV2 audio chain — with all 5 emit targets of ADR 0013 in place
// (wave 1: dp / wave 6: front / wave 7: flow, dec, voice). **voice green = the whole SBV2 chain
// works** (front emits the durations, the host builds z_p, voice emits the waveform).
//
// The tiny golden (tests/e2e_golden_test.ts) covers "the coverage of the op contracts" and the
// real-weight DeBERTa (tests/e2e_deberta_test.ts) covers "numerical agreement of the 24 text-side
// layers"; this one covers **real weights on the audio-chain side**.
// The containers and goldens are outside the repository (weights at the 251 MB scale); where each
// one is read from — the distribution mirror, the test-asset dataset or the exporter's series — is
// in "Where the assets come from" below. The series and the goldens are generated by
// `tools/export-recipes/sbv2/export.py` (GENERATE_COMMAND below is the source of the command).
//
// It is **parameterized by series (storage dtype)** — the f32 series / the f16 series (ADR 0018) /
// the i8 series (ADR 0019's per-channel w8 storage, f32 compute) run through the same structure,
// and **only the per-target tolerances are derived from measurements per series**. Tolerances are
// not reused across series (re-deriving one would silently move the other). The goldens of the
// compressed series are taken with **the weights after fake-quant**, so every series' error looks
// at "implementation differences only" (the quality of the quantization itself belongs to the
// listening gate).
//
// Where the assets are absent **that series SKIPs**. ADR 0005's "all-SKIP is an explicit FAIL"
// guard (tests/gpu_gate_test.ts) looks only at *whether a GPU adapter exists*, independent of this
// SKIP. Conversely, assets that are **partially** present (missing targets / missing cases) FAIL
// rather than SKIP (the "asset completeness" test below) — that would be a silent apparent
// success.
//
// Upstream parity is opt-in (helpers/upstream-parity.ts): the default run keeps the asset
// completeness gates and the per-case structure checks (tolerance table length, storage dtype set,
// io keys, output shape / dtype on the real GPU); the per-output tolerance comparison with the
// torch CPU goldens runs only with KARUME_UPSTREAM_PARITY=1.
//
// ## Where the assets come from (ADR 0139)
//
// The distribution `models/karume-sbv2-jvnv/` ships only the front and voice graphs, in f16 and
// i8 storage among others; its F1 front / voice containers are byte-identical to those of the f16
// and i8 series. Those four (series × target) pairs are default-lane cases: the container is read
// from the mirror through its manifest ({@link Sbv2Series.mirrorQuant}), and the goldens from the
// test-asset root, `goldenDir(<series>)/<target>/io.*` = `outputs/test-assets/goldens/…`
// (fetched with `node tools/test-assets/fetch.ts`). Everything else — the dp / flow / dec graphs
// and the whole f32 series — is not shipped: implementation-time series checks that read
// `outputs/series/` only with `KARUME_SERIES=1` and SKIP explicitly without it (decision 6).
// Each case SKIPs explicitly when the assets it reads are absent — except a golden absent from a
// complete fetch of the pinned dataset (`testAssetsFetched()`), which FAILs: the dataset at the pin
// lacks it. The tolerance table is checked against EXPECTED_TARGETS in every lane (it reads no
// asset).

