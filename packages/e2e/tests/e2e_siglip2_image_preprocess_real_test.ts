// Parity check of the image preprocessing layer (src/image/preprocess.ts) against the Python
// source of truth — the **real-image** part.
//
// Where the synthetic-fixture side (image_preprocess_test.ts) "pins the kernel's signature with
// asset-free synthetic images of about 22×33", this one pins **one real-size point: 1024×1024 real
// images downscaled to 224 / 384**. Both the scale (4.6× / 2.7×) and the nature of the picture (the
// natural gradations of a generated image) differ from the fixtures, so their mismatch rate and
// tolerance do not carry over as is (the measurements are in the derivation table below).
//
// The comparison target is **the Python-side `pixel_values` baked into the SigLIP2 goldens**
// (`input.pixel_values` of `goldenDir(<series>)/io.photo-*.safetensors` — ADR 0139), generated by
// `tools/export-recipes/siglip2/export.py --real-images` from transformers'
// `SiglipImageProcessor` (`TorchvisionBackend`), the source of truth. The images are the four
// Anima generations frozen by hand in the test-asset corpus (`corpusDir("anima")`); they cannot
// be regenerated byte for byte.
//
// ## The claim this check owns, and the split with the runtime side
//
// This check used to live together with the real-image cases of
// `packages/runtime/tests/e2e_siglip2_test.ts` (inference ran on `pixel_values` from the TS
// preprocessing, and one test looked at both the input side and the output side). It was split in
// two:
//
//  - **Input side (here)**: "the same PNG gives the same `pixel_values` as Python" — a pure parity
//    of the preprocessing layer alone, needing neither a GPU nor the model itself (350 MB to
//    1.7 GB).
//  - **Output side (runtime)**: the real-GPU fidelity with the `pixel_values` baked into the golden
//    as the input.
//
// The end-to-end claim "pass a PNG and get the same embedding as Python" is held by the
// **composition** of the two (this one guarantees an input difference ≤ {@link PIXEL_ATOL}, the
// runtime side guarantees the fidelity on that input). The reason for the split is the dependency
// direction — the runtime test imported the models implementation by a relative path (backwards).
//
// ## Derivation of the tolerance (measured 2026-08-14, raw comparison `atol=rtol=0`)
//
// One uint8 LSB is `1 / 127.5 = 7.8431e-3` after normalization, plus the rounding of the cast to
// f32. Measured over 8 cases (2 series × 4 real images):
//
// | Series | Case            | maxAbs     | Differing / all    | Rate   |
// | ------ | --------------- | ---------- | ------------------ | ------ |
// | base   | photo-portrait  | 7.84317e-3 | 204 / 150,528      | 0.136% |
// | base   | photo-landscape | 7.84314e-3 | 220 / 150,528      | 0.146% |
// | base   | photo-corridor  | 7.84315e-3 | 198 / 150,528      | 0.132% |
// | base   | photo-street    | 7.84315e-3 | 139 / 150,528      | 0.092% |
// | so400m | photo-portrait  | 7.84317e-3 | 3,817 / 442,368    | 0.863% |
// | so400m | photo-landscape | 7.84317e-3 | 3,681 / 442,368    | 0.832% |
// | so400m | photo-corridor  | 7.84317e-3 | 4,000 / 442,368    | 0.904% |
// | so400m | photo-street    | 7.84317e-3 | 3,502 / 442,368    | 0.792% |
//
// maxAbs is exactly 1 LSB in all 8 cases (the TS side accumulates in f64 and torchvision in f32,
// so only the samples sitting on a rounding boundary move by 1 — the derivation in detail is at the
// top of image_preprocess_test.ts). **The mismatch rate is 6× higher on the 384 side** because the
// milder scale (a 2.7× downscale) puts more samples on rounding boundaries, and it is also of
// another order than the fixture side's measured 0.23%. That is why the values are measured here
// rather than shared.
//
// ## Environments without the assets
//
// The goldens (`goldenDir(<series>)`) and the PNGs (`corpusDir("anima")`) live in the test-asset
// root, outside git (fetched with `node tools/test-assets/fetch.ts` — ADR 0139). The goldens can be
// regenerated by exporting again; the PNGs are frozen by hand and cannot be regenerated byte for
// byte. **None present while the test-asset root is not a complete fetch of the pin = explicit
// SKIP** (the assets gate is red then); **absent from a complete fetch = FAIL** (the dataset at the
// pin lacks it); **partially missing = FAIL** (rounding a gap to SKIP would let assets lost
// mid-regeneration pass silently). The same rule as the runtime-side e2e.

import { isNotFound, readFile, statSync } from "@karume/test-support/fs";
import { test } from "vite-plus/test";
import { assert, assertEquals } from "@std/assert";
import { parseSafetensors } from "@karume/runtime";
import { normalizeToNchw, resizeRgb8 } from "../../models/src/image/preprocess.ts";
// NOTE: by design karume itself has no PNG decoder (the module doc of preprocess.ts — the entry
// point is an RGB8 pixel array). A tool used only so the tests can read real images is borrowed
// from under the runtime's tests. models → runtime is a dependency in the **forward** direction,
// and both exclude `tests/` from publishing (`publish.exclude` in packages/*/deno.json), so the
// published packages are unaffected.
import { decodePng } from "@karume/test-support/png-decode";
import {
  corpusDir,
  goldenDir,
  TEST_ASSETS,
  testAssetsFetched,
} from "@karume/test-support/test-assets";

/**
 * The tolerance of the whole path (PNG → resize → normalize): the width of one uint8 LSB mapped to
 * `1 / 127.5` after normalization; measured 7.84314e-3 to 7.84317e-3 in all 8 cases (= always
 * exactly 1 LSB). The value adds a slight margin on top — the derivation table is at the top of
 * the file.
 *
 * It came out the same as `PIXEL_ATOL` in `image_preprocess_test.ts`, but it is **not shared**
 * (that one is for synthetic images of about 22×33, this one for 1024×1024 real images; the scale
 * and the nature of the picture differ. Re-measuring one must not silently move the other).
 *
 * Implementation differences that move by 2 LSB or more (mixed-up rounding, a wrong interpolation
 * kernel, reversed channel order, a wrong resolution) cross this threshold. An error of the
 * **every pixel off by 1** kind is not caught by this check; the mismatch-rate cap of
 * `image_preprocess_test.ts` (`MISMATCH_RATE_CAP`) covers it.
 */
const PIXEL_ATOL = 7.85e-3;

/**
 * The normalization constants of the preprocessing. mean = std = 0.5 for both models (the source
 * of truth is `preprocessor_config.json`).
 */
const IMAGE_MEAN: readonly [number, number, number] = [0.5, 0.5, 0.5];
const IMAGE_STD: readonly [number, number, number] = [0.5, 0.5, 0.5];

/**
 * The series (= models) with goldens. The resolution is **not written here** — it is taken from
 * the shape of the golden's `pixel_values` (writing 224 / 384 here would silently build a different
 * picture for the other one and hollow out the comparison).
 */
const SERIES = ["siglip2-base-patch16-224", "siglip2-so400m-patch14-384"] as const;

/**
 * The real-image cases. The source of truth for the case name ↔ file name mapping is
 * `REAL_CASES` in `tools/export-recipes/siglip2/export.py`; for the images themselves (prompt /
 * seed / resolution), `examples/anima/eval-images.ts`.
 * **Fixed here rather than enumerated** — relying on an enumeration, cases would silently vanish in
 * an environment that generated only some of them, giving "green but unchecked".
 */
const REAL_CASES = [
  { name: "photo-portrait", file: "anima-default-1024x1024-defaultstep-seed42.png" },
  { name: "photo-landscape", file: "anima-default-1024x1024-defaultstep-seed43.png" },
  { name: "photo-corridor", file: "anima-default-1024x1024-defaultstep-seed44.png" },
  { name: "photo-street", file: "anima-default-1024x1024-defaultstep-seed45.png" },
] as const;

/**
 * The key of the golden's input tensor (the source of truth is `INPUT_NAME` in
 * `tools/export-recipes/siglip2/export.py`).
 */
const PIXEL_INPUT_KEY = "input.pixel_values";

/**
 * The `__metadata__` fields of a real-image golden (the source of truth is the constants of the
 * same names in `tools/export-recipes/siglip2/export.py`).
 */
const SOURCE_IMAGE_KEY = "source_image";
const SOURCE_SHA256_KEY = "source_sha256";

/** The real-image corpus of the inputs (copies frozen by hand — the test-asset dataset's `corpus/anima/`). */
const CORPUS_DIR = corpusDir("anima");
/** The command that fetches the goldens and the corpus (pasted into the skip warnings). */
const FETCH_COMMAND = "node tools/test-assets/fetch.ts";

const goldenUrl = (series: string, caseName: string): URL =>
  new URL(`io.${caseName}.safetensors`, goldenDir(series));

/** The command that regenerates the goldens (`--real-images` uses another group). */
const generateCommand = (series: string): string =>
  "cd tools/export-recipes && uv run --group siglip2-preprocess python -m siglip2.export" +
  ` --real-images --model-dir ../../inputs/siglip2/${series}`;

/**
 * Whether the file exists.
 * MUST: anything other than NotFound propagates — reading a permission error or the like as "no
 * asset" would quietly turn a check that never ran green as a SKIP.
 */
const exists = (url: URL): boolean => {
  try {
    return statSync(url).isFile;
  } catch (cause) {
    if (isNotFound(cause)) return false;
    throw cause;
  }
};

/** Counted synchronously, since registration needs it (used for the `test.skipIf` decision). */
const goldenCount = (series: string): number =>
  REAL_CASES.filter((entry) => exists(goldenUrl(series, entry.name))).length;

const imageCount = REAL_CASES.filter((entry) => exists(new URL(entry.file, CORPUS_DIR))).length;

/**
 * Whether `outputs/test-assets/` holds a complete fetch of the pinned revision. Then a golden or an
 * image that is absent is a FAIL (the dataset at the pin lacks it), not a SKIP.
 */
const FETCHED = testAssetsFetched();

/**
 * Asserts that a test asset the case reads is present. A case reaches this with the asset absent
 * when the test-asset root is a complete fetch (otherwise it SKIPs) or a partial one.
 */
const assertAssetPresent = (url: URL): void =>
  assert(
    exists(url),
    FETCHED
      ? `${url.pathname} is absent, but outputs/test-assets/ holds a complete fetch of ` +
          `${TEST_ASSETS.repo}@${TEST_ASSETS.revision}: the dataset at the pin lacks it`
      : `${url.pathname} is absent (fetch: ${FETCH_COMMAND})`,
  );

/** The title suffix of a case that SKIPs for want of an asset, so the test list says why. */
const NOT_FETCHED = " (SKIP: test assets not fetched)";

const readBytes = (url: URL): Promise<Uint8Array<ArrayBuffer>> => readFile(url);

const sha256Hex = async (bytes: Uint8Array<ArrayBuffer>): Promise<string> =>
  Array.from(new Uint8Array(await crypto.subtle.digest("SHA-256", bytes)))
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");

for (const series of SERIES) {
  const goldens = goldenCount(series);
  /**
   * Whether the completeness test runs: some golden or image is present, or the root is a complete
   * fetch of the pin (then nothing may be missing). Otherwise the assets were not fetched.
   */
  const anyAsset = goldens > 0 || imageCount > 0 || FETCHED;
  const runnable = (goldens > 0 && imageCount > 0) || FETCHED;

  if (!runnable) {
    console.warn(
      `[karume] skipping the real-image preprocessing parity (${series}) (goldens ${goldens}/` +
        `${REAL_CASES.length}, images ${imageCount}/${REAL_CASES.length}). ` +
        `Fetch: ${FETCH_COMMAND}`,
    );
  }

  test.skipIf(!anyAsset)(
    `real-image preprocessing assets: ${series} — the goldens and the PNGs are complete${anyAsset ? "" : NOT_FETCHED}`,
    () => {
      if (FETCHED) {
        for (const entry of REAL_CASES) {
          assertAssetPresent(goldenUrl(series, entry.name));
          assertAssetPresent(new URL(entry.file, CORPUS_DIR));
        }
      }
      assert(
        goldens === 0 || goldens === REAL_CASES.length,
        `${series} has ${goldens}/${REAL_CASES.length} real-image goldens` +
          ` (regenerate: ${generateCommand(series)})`,
      );
      assert(
        imageCount === 0 || imageCount === REAL_CASES.length,
        `${CORPUS_DIR.pathname} has ${imageCount}/${REAL_CASES.length} real images` +
          `（fetch again: ${FETCH_COMMAND}）`,
      );
    },
  );

  for (const entry of REAL_CASES) {
    test.skipIf(!runnable)(
      `real-image preprocessing parity: ${series} / ${entry.name} (the TS f64 path vs torchvision)` +
        (runnable ? "" : NOT_FETCHED),
      async () => {
        assertAssetPresent(goldenUrl(series, entry.name));
        assertAssetPresent(new URL(entry.file, CORPUS_DIR));
        const [goldenBytes, png] = await Promise.all([
          readBytes(goldenUrl(series, entry.name)),
          readBytes(new URL(entry.file, CORPUS_DIR)),
        ]);
        const io = parseSafetensors(
          goldenBytes.buffer.slice(
            goldenBytes.byteOffset,
            goldenBytes.byteOffset + goldenBytes.byteLength,
          ),
        );

        // ① The image the golden was taken from is the image being read now. A **difference the
        // tolerance does not absorb** (the generation script was rerun but the golden was not
        // regenerated) fails by name before the comparison. If this loosened, "two different
        // images compared, and green" could happen.
        assertEquals(
          io.metadata.get(SOURCE_IMAGE_KEY),
          entry.file,
          "the source image the golden points to",
        );
        assertEquals(
          io.metadata.get(SOURCE_SHA256_KEY),
          await sha256Hex(png),
          `${entry.file} differs from the image the golden was taken from (regenerate: ${generateCommand(series)})`,
        );

        const view = io.tensors.get(PIXEL_INPUT_KEY);
        assert(view !== undefined, `${PIXEL_INPUT_KEY} is not in the golden`);
        assertEquals(view.dtype, "F32", `${PIXEL_INPUT_KEY} storage dtype`);
        assertEquals(view.shape.length, 4, `${PIXEL_INPUT_KEY} rank`);
        const [batch, channels, height, width] = view.shape;
        assertEquals([batch, channels], [1, 3], `${PIXEL_INPUT_KEY} leading 2 axes`);
        const expected = new Float32Array(io.buffer, view.byteOffset, view.byteLength / 4);

        // ② The TS-side path (PNG decode → resize → fused normalization).
        const decoded = await decodePng(png, entry.file);
        const got = normalizeToNchw(resizeRgb8(decoded, width, height), IMAGE_MEAN, IMAGE_STD);

        assertEquals(got.length, expected.length, `${entry.name}: pixel_values length`);
        let maxAbs = 0;
        let worst = 0;
        let nonFinite = 0;
        for (let index = 0; index < got.length; index += 1) {
          if (!Number.isFinite(got[index]) || !Number.isFinite(expected[index])) {
            nonFinite += 1;
            continue;
          }
          const delta = Math.abs(got[index] - expected[index]);
          if (delta > maxAbs) {
            maxAbs = delta;
            worst = index;
          }
        }
        // MUST: NaN / ±Inf fail. A naive difference check would let NaN pass disguised as "a
        // difference of 0".
        assertEquals(nonFinite, 0, `${entry.name}: non-finite samples in pixel_values`);
        assert(
          maxAbs <= PIXEL_ATOL,
          `${series} / ${entry.name}: pixel_values maxAbs=${maxAbs}` +
            ` (sample ${worst}: ${got[worst]} vs ${expected[worst]}) exceeded ${PIXEL_ATOL}`,
        );
      },
    );
  }
}
