// Pins the **byte parity** of umT5's relative-position bucket tables between the host's TS
// generator (src/umt5/relative-position.ts) and the Python source of truth (the recipe
// `wan/umt5_patch.py` — it calls the upstream `_relative_position_bucket`) (ADR 0119 decision 3 —
// the same job as sbv2_rel_pos_parity_test.ts).
//
// The tables are graph inputs, and the golden tables are made by Python too. If the formulas
// diverge, a bias for a different distance is added with valid shapes, and if the host and the
// golden share the same error the E2E slips through as well, so this compares them directly,
// separately from the E2E. Upstream uses f32 `log` and the host f64 `Math.log` — this is the only
// place where real data pins that truncation does not diverge at the boundaries.
//
// The fixtures are in `fixtures/wan-umt5/` (generated by
// tools/export-recipes/wan/umt5_host_fixture.py):
//  - `bucket_by_distance` — every distance from −511 to 511 (for naming elements)
//  - tables for representative valid lengths (lengths across bucket boundaries and the fixed
//    prompts' lengths)
//  - a digest of every table for valid lengths 2 to 512 (the SHA-256 of the per-table SHA-256s
//    concatenated in ascending order)
// Needs neither a GPU nor real assets.

import { readFile, readTextFile } from "@karume/test-support/fs";
import { test } from "vite-plus/test";
import { assert, assertEquals, assertThrows } from "@std/assert";
import { parseSafetensors } from "@karume/runtime";
import {
  buildUmt5RelativePositionBuckets,
  UMT5_MAX_LENGTH,
  UMT5_MIN_TOKENS,
  UMT5_RELATIVE_POSITION,
} from "../src/umt5/relative-position.ts";

const FIXTURE_DIR = new URL("./fixtures/wan-umt5/", import.meta.url);

type RelativePositionMeta = {
  readonly num_buckets: number;
  readonly max_distance: number;
  readonly bidirectional: boolean;
  readonly min_length: number;
  readonly max_length: number;
  readonly distance_offset: number;
  readonly representative_lengths: readonly number[];
  readonly digest: string;
};

const meta = JSON.parse(
  await readTextFile(new URL("relative-position.json", FIXTURE_DIR)),
) as RelativePositionMeta;
const fixtureBytes = await readFile(new URL("relative-position.safetensors", FIXTURE_DIR));
const tensors = parseSafetensors(
  fixtureBytes.buffer.slice(
    fixtureBytes.byteOffset,
    fixtureBytes.byteOffset + fixtureBytes.byteLength,
  ) as ArrayBuffer,
);

/** An I32 tensor of the fixture (fails if missing or not I32). */
const fixtureInt32 = (key: string): { shape: readonly number[]; data: Int32Array } => {
  const view = tensors.tensors.get(key);
  assert(view !== undefined, `the fixture has no '${key}'`);
  assertEquals(view.dtype, "I32", `dtype of '${key}'`);
  return {
    shape: view.shape,
    data: new Int32Array(tensors.buffer, view.byteOffset, view.byteLength / 4),
  };
};

/** Exact element-wise equality (names the first position that differs). */
const assertSameElements = (
  actual: ArrayLike<number>,
  expected: ArrayLike<number>,
  where: (index: number) => string,
): void => {
  assertEquals(actual.length, expected.length, "element count");
  for (let index = 0; index < expected.length; index += 1) {
    if (actual[index] !== expected[index]) {
      throw new Error(`${where(index)} differs (TS=${actual[index]} / Python=${expected[index]})`);
    }
  }
};

const hex = (bytes: ArrayBuffer): string =>
  [...new Uint8Array(bytes)].map((byte) => byte.toString(16).padStart(2, "0")).join("");

test("umT5's bucket configuration and valid-length range match the fixture (the pinned config)", () => {
  assertEquals(
    {
      numBuckets: UMT5_RELATIVE_POSITION.numBuckets,
      maxDistance: UMT5_RELATIVE_POSITION.maxDistance,
      bidirectional: true,
      minLength: UMT5_MIN_TOKENS,
      maxLength: UMT5_MAX_LENGTH,
    },
    {
      numBuckets: meta.num_buckets,
      maxDistance: meta.max_distance,
      bidirectional: meta.bidirectional,
      minLength: meta.min_length,
      maxLength: meta.max_length,
    },
  );
});

test("umT5's buckets for distances −511 to 511 match the upstream formula", () => {
  // In the table at the maximum length, row 0 holds distances 0 to 511 and column 0 distances 0 to
  // −511 (table[i][j] = bucket(j − i)).
  const table = buildUmt5RelativePositionBuckets(UMT5_MAX_LENGTH).data;
  const expected = fixtureInt32("bucket_by_distance");
  assertEquals(expected.shape, [2 * UMT5_MAX_LENGTH - 1]);
  const actual = new Int32Array(expected.data.length);
  for (let distance = meta.distance_offset; distance < UMT5_MAX_LENGTH; distance += 1) {
    actual[distance - meta.distance_offset] =
      distance >= 0 ? table[distance] : table[-distance * UMT5_MAX_LENGTH];
  }
  assertSameElements(
    actual,
    expected.data,
    (index) => `bucket for distance ${index + meta.distance_offset}`,
  );
});

for (const length of meta.representative_lengths) {
  test(`umT5's bucket table L=${length} is byte-identical to Python's`, () => {
    const built = buildUmt5RelativePositionBuckets(length);
    const expected = fixtureInt32(`table.l${String(length).padStart(3, "0")}`);
    assertEquals(built.dtype, "i32");
    assertEquals(built.shape, [length, length]);
    assertEquals(expected.shape, [length, length]);
    assertSameElements(
      built.data,
      expected.data,
      (index) => `L=${length} at [${Math.floor(index / length)}][${index % length}]`,
    );
  });
}

test("umT5's bucket tables: the digest of every table for valid lengths 2 to 512 matches Python", async () => {
  // The digest is defined over the tables' i32 little-endian bytes (the fixture's doc). An
  // Int32Array holds its contents in the engine's byte order, so a big-endian machine stops before
  // comparing.
  assertEquals(new Uint8Array(new Uint32Array([1]).buffer)[0], 1, "not a little-endian machine");
  assertEquals([meta.min_length, meta.max_length], [UMT5_MIN_TOKENS, UMT5_MAX_LENGTH]);
  const chained = new Uint8Array(32 * (UMT5_MAX_LENGTH - UMT5_MIN_TOKENS + 1));
  for (let length = UMT5_MIN_TOKENS; length <= UMT5_MAX_LENGTH; length += 1) {
    const { data } = buildUmt5RelativePositionBuckets(length);
    const digest = await crypto.subtle.digest("SHA-256", data);
    chained.set(new Uint8Array(digest), 32 * (length - UMT5_MIN_TOKENS));
  }
  assertEquals(hex(await crypto.subtle.digest("SHA-256", chained)), meta.digest);
});

test("buildUmt5RelativePositionBuckets: accepted valid lengths (2 to 512, as the graph's symbolic dimension)", () => {
  for (const length of [0, 1, UMT5_MAX_LENGTH + 1, 2.5, Number.NaN]) {
    assertThrows(
      () => buildUmt5RelativePositionBuckets(length),
      RangeError,
      "is not an integer in",
      `valid length ${length}`,
    );
  }
});
